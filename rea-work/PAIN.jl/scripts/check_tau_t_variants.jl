#!/usr/bin/env julia
# Plan 19e: τ_t of the Phase III sidewall stack at 100–400 Hz under the variants listed in the plan, plus NASA's own trim loss factor.
# Criteria fixed in IMPLEMENTATION_PLAN.md (phase 19, 2026-10-20) before the run. The transfer matrices are rebuilt locally so no
# `src/` constant is changed; the base row is checked against PAIN's own `trim_tau`.
using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using PAIN, Printf, LinearAlgebra

function elmat(el, ω, sgn)
    if el isa PAIN.InsulationLayer
        p = PAIN.insulation_properties(el.material, ω / 2π)
        k = 2π / p.lambda_m
        x = complex(p.alpha_Np_per_m, -k) * el.thickness
        C, S = cosh(x), sinh(x)
        W = p.W_abs * cis(sgn * p.phi_rad)
        return ComplexF64[C im*ω*W*S; -im*S/(ω*W) C]
    else
        return ComplexF64[1 ω^2 * el.m * (1 + im * el.η); 0 1]
    end
end
function stackM(st, ω, sgn)
    M = ComplexF64[1 0; 0 1]
    for el in st.elements; M = elmat(el, ω, sgn) * M; end
    return M
end
tau_ins(st, ω, sgn) = 1 / abs2(stackM(st, ω, sgn)[1, 1])
function xi(st, ω, mw, sgn; ρ0=1.225, c0=340.0)   # Re β, Eq. (A.16)
    M = stackM(st, ω, sgn); a11, a12, a21, a22 = M[1,1], M[1,2], M[2,1], M[2,2]
    Z1 = ρ0 * c0 - im * ω * mw
    return real(ρ0 * c0 * (-ω^2 * a21 * Z1 + im * ω * a22) / (im * ω * a11 * Z1 + a12))
end

fs = [100, 125, 160, 200, 250, 315, 400]
fgrid = 10 .^ range(2, log10(6300); length=200)
variants = [
    ("base (registered: η = 0.05, facing on cabin side, septum, W sign +)", (;), +1),
    ("W_PHASE_SIGN flipped", (;), -1),
    ("facing on the skin side", (facing_side=:skin,), +1),
    ("septum removed", (septum_mass=0.0,), +1),
    ("η_lining = 0.5 (NASA's trim loss factor for the E-16 predictions)", (η_lining=0.5,), +1),
    ("η_lining = 1.0 (second E-14/E-15 curve)", (η_lining=1.0,), +1),
    ("η_lining = 0.5, facing on the skin side", (η_lining=0.5, facing_side=:skin), +1),
]
io = IOBuffer()
println(io, "# τ_t of the Phase III sidewall at 100–400 Hz: variants (plan 19e)\n")
println(io, "Generated by `scripts/check_tau_t_variants.jl`. Criteria fixed 2026-10-20 before the run (`IMPLEMENTATION_PLAN.md`, phase 19): each variant's τ_t recorded; a variant that makes τ_t ≤ 1 at 200 Hz is a finding, not adopted; if NASA prints a τ_t curve for Phase III, within 3 dB of it. Matrices rebuilt in the script (no `src/` change); τ_t = |a11|⁻² + τ_t^m (Eq. A.22) with the mechanical path of `phase3_trim`.\n")
println(io, "**NASA's printed τ_t:** none. Figures A-2, E-13, E-14, E-15 and E-25 print the insulation properties, absorption and loss factors, not a τ_t curve (checked against the list of figure captions of CR-3813 App. A and E), so the 3 dB comparison has no target.\n")
println(io, "**Trim loss factor used by NASA (CR-3813 App. E p. E-24, read from the page image):** \"The two calculated loss factor spectra in Figure E-15 assumed trim loss factors of 0.5 and 1.0\" and, for the predicted interior levels of Figs. E-16/E-17: \"with an assumed structural loss factor for the trim of η_T = 0.5\". The registered 18b run used `phase3_trim`'s default η_lining = 0.05 (register f, chosen for the aircraft case), not NASA's 0.5.\n")
println(io, "| Variant | " * join(["τ_t $(f) Hz" for f in fs], " | ") * " | τ_t at 200 Hz ≤ 1? | min ξ = Re β, 100–6300 Hz | passive (Re β ≥ 0) |")
println(io, "|---|" * "---:|"^length(fs) * "---|---:|---|")
base_check = nothing
for (lab, kw, sgn) in variants
    p3 = phase3_trim(; kw...)
    τ = [tau_ins(p3.sidewall, 2π * f, sgn) + PAIN.trim_tau_mechanical(p3.mech, 2π * f) for f in fs]
    if base_check === nothing
        ref = [PAIN.trim_tau(p3.sidewall, 2π * f; mech=p3.mech) for f in fs]
        global base_check = maximum(abs.(τ ./ ref .- 1))
    end
    ξmin = minimum(xi(p3.sidewall, 2π * f, p3.m_wall, sgn) for f in fgrid)
    @printf(io, "| %s | %s | %s | %.4f | %s |\n", lab, join([@sprintf("%.3g (%+.1f dB)", t, 10log10(t)) for t in τ], " | "),
            τ[4] <= 1 ? "**yes**" : "no", ξmin, ξmin >= 0 ? "yes" : "**no**")
end
@printf(io, "\nCheck: the base row equals PAIN's `trim_tau` to %.1e (relative).\n", base_check)
println(io, "\nτ_t > 1 is not excluded by Eq. (A.22) (the insulation term |a11|⁻² and the mechanical term are not bounded by 1); whether NASA's trim also exceeded 1 at 200 Hz is not printed. The 18b effect of the variants is run in 19f.")
out = joinpath(@__DIR__, "..", "..", "docs", "validation_reports", "tau_t_variants.md")
write(out, String(take!(io))); println(read(out, String))
