#!/usr/bin/env julia
# Plan phase 16: App. A trim and §3.8 loss factors against Figs. E-13, E-14, E-15.
# Statistic and pass rule fixed 2026-10-20 before this script was first run (VALIDATION_GUIDELINE §2.11.3). No tuning.
using Pkg
Pkg.activate(joinpath(@__DIR__, "..", ".."))
using PAIN
using Printf

const DATA = joinpath(@__DIR__, "..", "..", "..", "data", "cr3813")
const OUT = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "trim_loss_e13_e14_e15.md")

a, L, θ0d = 0.508, 1.803, 56.6
θ0 = deg2rad(θ0d)
fuse = FuselageGeometry(L, a, θ0d)
V = cabin_volume(fuse)
S = 2a * (π - θ0) * L
S_e = V / L
c0, ρ0 = 340.0, 1.225

e14 = PAIN._read_csv_numeric(joinpath(DATA, "e14_acoustic_loss_calculated.csv"))
e13 = PAIN._read_csv_numeric(joinpath(DATA, "e13_absorption_targets.csv"))
e14m = PAIN._read_csv_numeric(joinpath(DATA, "e14_acoustic_loss_targets.csv"))
e15m = PAIN._read_csv_numeric(joinpath(DATA, "e15_structural_loss_targets.csv"))

io = IOBuffer()
println(io, "# Phase 16 — App. A trim and §3.8 loss factors against Figs. E-13, E-14, E-15\n")
println(io, "Generated by `scripts/run/run_trim_loss_check.jl`. Statistic, inputs and pass rule fixed 2026-10-20 before the first run (`VALIDATION_GUIDELINE.md` §2.11.3). No parameter was tuned.\n")
println(io, "Phase III: a = $a m, L = $L m, θ0 = $(θ0d)°, V = $(round(V; digits=4)) m³, S = $(round(S; digits=3)) m², S_e = $(round(S_e; digits=4)) m². Insulation: Fig. A-2 (PF-105), digitized.\n")

# ---------------- E-14: Eq. (78) vs NASA's calculated curves (V-CODE) ----------------
pass_counts = Dict{Float64,Int}()
for (col, ηT) in ((:eta_calc_trim0p5, 0.5), (:eta_calc_trim1p0, 1.0))
    p3 = phase3_trim(; η_lining=ηT)
    println(io, "## Fig. E-14 calculated curve, trim loss factor $ηT — Eq. (78) with ξ, ξ_e from Eq. (A.16) (V-CODE, ±25 % per band)\n")
    println(io, "| f [Hz] | ξ | ξ_e | η̄ Eq.(78) | η̄ NASA E-14 | ratio | ±25 % | ᾱ Eq.(24) | τ_t Eq.(A.22) |")
    println(io, "|---:|---:|---:|---:|---:|---:|:--:|---:|---:|")
    npass = 0
    for i in eachindex(e14[:f_Hz])
        f = e14[:f_Hz][i]; ω = 2π * f
        ξ = trim_conductance(p3.sidewall, ω, p3.m_wall; ρ0, c0)
        ξe = trim_conductance(p3.ends, ω, Inf; ρ0, c0)
        η = acoustic_loss_average(ω; V, S, S_e, ξ, ξ_e=ξe, c0)
        ref = e14[col][i]
        ratio = η / ref
        ok = abs(ratio - 1) ≤ 0.25
        npass += ok
        ᾱ = absorption_from_loss_factor(η, ω; V, S=S + 2S_e, c0)
        τ = trim_tau(p3.sidewall, ω; mech=p3.mech)
        @printf(io, "| %g | %.4f | %.4f | %.4f | %.4f | %.2f | %s | %.3f | %.4g |\n", f, ξ, ξe, η, ref, ratio, ok ? "PASS" : "FAIL", ᾱ, τ)
    end
    pass_counts[ηT] = npass
    println(io, "\n**Bands passing: $npass of $(length(e14[:f_Hz])).**\n")
end

# ---------------- E-14 diagnostic: Eq. (77) mode average (no pass mark) ----------------
println(io, "## Fig. E-14 diagnostic: mean of Eq. (77) η_n over the cabin modes in each band (no pass mark), trim loss factor 0.5\n")
cy = cyl2d_modes(θ0d; n_modes=20, NY=10, c0=c0)
p3 = phase3_trim(; η_lining=0.5)
modes3d = cabin_modes_3d(cy, a, L, axial_truncation(2π * 6300, L, c0); c0=c0)
byidx = Dict(m.index => m for m in cy.modes)
println(io, "| f [Hz] | modes in band | mean η_n Eq.(77) | η̄ Eq.(78) |")
println(io, "|---:|---:|---:|---:|")
for i in eachindex(e14[:f_Hz])
    f = e14[:f_Hz][i]
    lo, hi = f / 2^(1 / 6), f * 2^(1 / 6)
    vals = Float64[]
    for m in modes3d
        (lo ≤ m.f_Hz < hi) || continue
        m.f_Hz < 100 && continue   # below the Fig. A-2 range (100–6300 Hz); not extrapolated
        ω_n = 2π * m.f_Hz
        ξ = trim_conductance(p3.sidewall, ω_n, p3.m_wall; ρ0, c0)
        ξe = trim_conductance(p3.ends, ω_n, Inf; ρ0, c0)
        push!(vals, acoustic_loss_modal(byidx[m.i], m.q, ω_n, ω_n; a, L, V, c0, ξ, ξ_e=ξe).η_n)
    end
    ω = 2π * f
    η78 = acoustic_loss_average(ω; V, S, S_e, ξ=trim_conductance(p3.sidewall, ω, p3.m_wall; ρ0, c0), ξ_e=trim_conductance(p3.ends, ω, Inf; ρ0, c0), c0)
    @printf(io, "| %g | %d | %s | %.4f |\n", f, length(vals), isempty(vals) ? "—" : @sprintf("%.4f", sum(vals) / length(vals)), η78)
end
println(io)

# ---------------- E-13: measured absorption vs Eq. (24) (V-EXP, no pass mark) ----------------
println(io, "## Fig. E-13 (measured points only; no calculated curve exists in the figure) vs ᾱ from Eqs. (78) and (24), trim loss factor 0.5 (V-EXP, no pass mark)\n")
println(io, "| f [Hz] | ᾱ measured | ᾱ Eq.(24) |")
println(io, "|---:|---:|---:|")
for i in eachindex(e13[:f_Hz])
    f = e13[:f_Hz][i]; ω = 2π * f
    ξ = trim_conductance(p3.sidewall, ω, p3.m_wall; ρ0, c0)
    ξe = trim_conductance(p3.ends, ω, Inf; ρ0, c0)
    η = acoustic_loss_average(ω; V, S, S_e, ξ, ξ_e=ξe, c0)
    @printf(io, "| %g | %.3f | %.3f |\n", f, e13[:alpha_meas][i], absorption_from_loss_factor(η, ω; V, S=S + 2S_e, c0))
end
println(io)

# ---------------- E-14 measured vs Eq. (78) (V-EXP, no pass mark) ----------------
println(io, "## Fig. E-14 measured points vs Eq. (78), trim loss factor 0.5 (V-EXP, no pass mark)\n")
println(io, "| f [Hz] | η measured (mid-envelope) | η̄ Eq.(78) |")
println(io, "|---:|---:|---:|")
for i in eachindex(e14m[:f_Hz])
    f = e14m[:f_Hz][i]; ω = 2π * f
    ξ = trim_conductance(p3.sidewall, ω, p3.m_wall; ρ0, c0)
    ξe = trim_conductance(p3.ends, ω, Inf; ρ0, c0)
    @printf(io, "| %g | %.3f | %.4f |\n", f, e14m[:eta_meas][i], acoustic_loss_average(ω; V, S, S_e, ξ, ξ_e=ξe, c0))
end
println(io)

# ---------------- E-15: structural loss factor η_r' (V-EXP, no pass mark) ----------------
println(io, "## Fig. E-15: structural loss factor with trim, η_r' of Eq. (82), for the 32 Table D-1 modes (V-EXP, no pass mark)\n")
println(io, "C = 3 (Eq. 80), M_r from Table D-1, m = $(round(p3.m_wall; digits=3)) kg/m². `mode-normalized` doubles the printed n > 0 and axial joint acceptances (see `ring_joint_acceptance`).\n")
println(io, "| mode | f_r [Hz] | η_r struc | η_r rad (printed) | η_r (printed) | η_r' (trim 0.5) | η_r' (trim 1.0) | η_r rad (mode-normalized) |")
println(io, "|---:|---:|---:|---:|---:|---:|---:|---:|")
sm = structural_modes_from_table_d1(; L=L, a=a, theta0_deg=θ0d, n_keep=32)
for m in sm.modes
    ωr = 2π * m.f_Hz
    ηs = structural_loss_vacuo(m.f_Hz)
    j2 = structural_joint_acceptance(m, ωr; a, L, c0)
    ηrad = radiation_loss_factor(j2, ωr; Abar=2π * a * L, m=p3.m_wall, ρ0, c0)
    j2n = structural_joint_acceptance(m, ωr; a, L, c0, mode_normalized=true)
    ηradn = radiation_loss_factor(j2n, ωr; Abar=2π * a * L, m=p3.m_wall, ρ0, c0)
    ηr = ηs + ηrad
    cols = String[]
    for ηT in (0.5, 1.0)
        p = phase3_trim(; η_lining=ηT)
        Cw = trim_Cw(p.sidewall, ωr)
        push!(cols, try @sprintf("%.4f", structural_loss_with_trim(ηr, ωr, p.m_wall, Cw)) catch e "error" end)
    end
    @printf(io, "| %d | %.1f | %.4f | %.4f | %.4f | %s | %s | %.4f |\n", m.index, m.f_Hz, ηs, ηrad, ηr, cols[1], cols[2], ηs + ηradn)
end
println(io, "\nFig. E-15 measured (digitized mid-envelope): " * join([@sprintf("%g Hz: %.3f", f, e15m[:eta_meas][i]) for (i, f) in enumerate(e15m[:f_Hz])], "; ") * ".\n")

write(OUT, String(take!(io)))
println("wrote $OUT")
println("E-14 bands passing: ", pass_counts)
