#!/usr/bin/env julia
# Plan 19d: does NASA's Ψ_G use the 160 stated grid points or points mirrored about θ = 0? The decision is taken from the text (report);
# the mirrored fields are run as diagnostics only, inside this process (no src/ change). A miss is a finding, not a reason to tune.
using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using PAIN, Printf
paths = default_e11_paths()
tg = PAIN._read_csv_numeric(joinpath(dirname(paths.A), "t1_interior_targets.csv"))
nasa = tg[:nasa_pain_pred_dB]
run18b() = run_pain_pipeline(; source=:e11, e11_amp_csv=paths.anopp_spl, n_harmonics=3, bpf_Hz=200.0, blocking=R1, trim=:phase3).spectrum.harmonic_SPL_dB

s0 = run18b()
φp = 90.0     # registered case: ℓ = 1 line at θ = φ_p (default of `propeller_freefield_grid`; Phase III test article)
@eval PAIN const _MIRROR = Ref{Any}(nothing)
@eval PAIN function generalized_force_sums(st::StructuralMode, H::Int, amps::Array{Float64,3}, phases::Array{Float64,3}, pts, fuse::FuselageGeometry)
    sc = 0.0; ss = 0.0
    for p in pts, θ in (p.theta_deg, _MIRROR[](p.theta_deg))
        A = amps[p.k, p.ell, H]; ϕ = phases[p.k, p.ell, H]
        ψ = structural_shell_psi(st, p.z, θ, fuse.L)
        sc += A * cos(ϕ) * ψ; ss += A * sin(ϕ) * ψ
    end
    return sc, ss
end
variants = ("mirrored about θ = 0 (bottom centerline): θ → −θ, same A and phase" => (θ -> -θ),
            "mirrored about the ℓ = 1 line: θ → 2φ_p − θ, same A and phase" => (θ -> 2φp - θ))
rows = []
for (label, f) in variants
    PAIN._MIRROR[] = f
    push!(rows, (label, Base.invokelatest(run18b)))
end

io = IOBuffer()
println(io, "# Grid mirroring \"above and below θ = 0\" (plan 19d)\n")
println(io, "Generated by `scripts/check_grid_mirroring.jl`. Decision from the text; mirrored fields are diagnostics (no `src/` change, the override lives in the script's process). Criterion fixed 2026-10-20 before the run: decision quoted from the text; if mirrored, the 18b numbers with a mirrored field recorded.\n")
println(io, "## Text read (page images)\n")
println(io, """
- **User Manual (CR-172425) §3, p. 8:** "The grid is defined over one-quarter of the periphery of the cylinder." x1 penetrates the fuselage perpendicularly and "that point of penetration will establish the line (ℓ = 1)"; positions for k = 1…k_max and **ℓ = 1, 10**: x1 = (r_p − a) + a{1 − cos[(ℓ−1)π/18]}, x2 = −a sin[(ℓ−1)π/18], x3 = (πa/18)(k_p − k).
- **User Manual Fig. 3 (p. 5):** 10 circumferential points ℓ = 1…10 on one side of the ℓ = 1 line, k = 1…16 axially (160 points), all on one quarter of the skin.
- **User Manual card 36 note (p. 34):** "The propeller pressure signature is defined at grid points on the upper quarter of the fuselage skin, and input, using a Fourier series analysis, as the amplitude and phase at the propeller harmonics for each grid point." Cards 38 onward: Hmax × kmax × 10 cards, one per (H, k, ℓ), ℓ = 1…10.
- **User Manual §5.4.3 item 7 (p. 37, printed output):** "Propeller Pressure Amplitude and Phase. Output for all grid points, both above and below θ = 0, for each propeller harmonic." This is a list of printed output; it does not say that the input field is mirrored, and θ = 0 is the bottom centerline in Fig. 2 while the input has no points other than ℓ = 1…10. The wording is **unresolved**: no text reads it as an instruction to mirror the field.
- **CR-3813 §3.4, p. 27:** "In the present model, the grid is confined to the side of the fuselage where the propeller is located." Ψ_G (Eq. 42) is the sum over these grid points m = (k, ℓ).

## Decision

**The 160 stated points are used; the field is not mirrored.** Basis: the input definition, the card-36 note, Fig. 3 and CR-3813 §3.4 all say one side only, and only item 7's output wording points the other way and says nothing about the input. The production code already does this (`generalized_force_sums` sums the 160 points). The item 7 wording stays recorded as unresolved and is not read as a mirroring instruction.

## Diagnostic: 18b with a mirrored field (not adopted)

Same inputs as 18b (R1 blocking, Phase III trim, ANOPP Table 8, GEXT off the ℓ = 1 line). Each of the 160 points gets a second point at the mirrored θ with the same amplitude and phase (the field is not symmetric in reality, so this is only a probe of the Ψ_G sum). NASA PAIN predictions: $(nasa[1]), $(nasa[2]), $(nasa[3]) dB.

| Field | H1 dB | H2 dB | H3 dB | vs NASA (dB) | within 4 dB |
|---|---:|---:|---:|---|---:|""")
@printf(io, "| 160 stated points (decision) | %.2f | %.2f | %.2f | %+.1f, %+.1f, %+.1f | %d of 3 |\n", s0..., (s0 .- nasa[1:3])..., count(abs.(s0 .- nasa[1:3]) .<= 4))
for (label, s) in rows
    @printf(io, "| %s | %.2f | %.2f | %.2f | %+.1f, %+.1f, %+.1f | %d of 3 |\n", label, s..., (s .- nasa[1:3])..., count(abs.(s .- nasa[1:3]) .<= 4))
end
println(io, "\nShifts against the decision row: " * join([@sprintf("%s: %+.2f, %+.2f, %+.2f dB", first(split(l, ":")), (s .- s0)...) for (l, s) in rows], "; ") * ".")
out = joinpath(@__DIR__, "..", "..", "docs", "validation_reports", "grid_mirroring.md")
write(out, String(take!(io))); println(read(out, String))
