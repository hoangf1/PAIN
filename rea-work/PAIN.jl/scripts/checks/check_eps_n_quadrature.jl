#!/usr/bin/env julia
# Plan 19c: ε_n for q > 0. Independent quadrature of the CYL2D mode shapes times cos²(qπz/L) over the cabin volume, compared with
# `cabin_eps_3d`; and the 18b effect of the alternative reading ε_n(q > 0) = ε_n(q = 0), recorded and not adopted.
# Criteria fixed in IMPLEMENTATION_PLAN.md (phase 19, 2026-10-20) before this script was first run. A miss is a finding, not a reason to tune.
using Pkg; Pkg.activate(joinpath(@__DIR__, "..", ".."))
using PAIN, Printf

const θ0_deg = 56.6                      # Phase III test article
cy = cyl2d_modes(θ0_deg; NY=10, c0=TABLE_C1_C0)
h = cy.h
θ0 = deg2rad(θ0_deg)
yfloor = -cos(θ0)
A_exact = π - θ0 + cos(θ0) * sin(θ0)     # unit radius

# Independent area quadrature: every point of a fine grid inside the true cabin (r ≤ 1, y ≥ floor) takes the value of the nearest
# node that exists in the mode's node set (Voronoi cell of that node), instead of the C(j) weights of Eq. (C.10). The mean of φ²
# over the sample points times the exact cabin area gives ∫φ² dA. Half cabin x ≥ 0 (φ² is symmetric).
function area_integral_phi2(mode)
    nodes = mode.phi_nodes
    dx = h / 60
    s = 0.0; ns = 0
    for x in dx/2:dx:1.0, y in yfloor+dx/2:dx:1.0
        hypot(x, y) <= 1 || continue
        m0, n0 = round(Int, x / h), round(Int, (y - yfloor) / h)
        best = Inf; val = 0.0
        for dm in -1:1, dn in -1:1
            k = (m0 + dm, n0 + dn)
            haskey(nodes, k) || continue
            d = hypot(x - k[1] * h, y - (yfloor + k[2] * h))
            d < best && (best = d; val = nodes[k])
        end
        isfinite(best) || error("no node near ($x, $y)")
        s += val^2; ns += 1
    end
    return A_exact * s / ns
end

# z factor by quadrature (midpoint, 4000 points over [0, L], L = 1; only the ratio to L matters)
zfac(q) = (zs = ((1:4000) .- 0.5) ./ 4000; sum(cospi.(q .* zs) .^ 2) / 4000)

io = IOBuffer()
println(io, "# ε_n for q > 0: quadrature check (plan 19c)\n")
println(io, "Generated by `scripts/checks/check_eps_n_quadrature.jl`. Phase III floor θ0 = 56.6°, NY = 10, first 10 cross-section modes (index 0–9), q = 0–3. Criteria fixed 2026-10-20 before the run (`IMPLEMENTATION_PLAN.md`, phase 19): quadrature equals `cabin_eps_3d` within 0.5 % for every (q, i); the printed text read and quoted; the 18b effect of ε_n(q > 0) = ε_n(q = 0) recorded, not adopted.\n")
println(io, "## Printed text (CR-3813 App. C, pp. C-6, C-7, PDF pages 86–87, read from the page images)\n")
println(io, "- p. C-6: ∫_V φ_qi²(ξ) dv = (L/2) ε_q Σ_j φ_i²(j) h² C(j).")
println(io, "- p. C-7: \"Also ε_q = 2 for q = 0; 1 for q > 0.\" Eq. (C.10): Φ_G(i) = Σ_j φ_i²(j) G² C(j). Eq. (C.11): ε_n = ε_qi = 2[π − θ0 + cosθ0 sinθ0] / (Φ_G(i) ε_q).")
println(io, "- Reading: with V = a²L[π − θ0 + cosθ0 sinθ0], ε_n = V/∫φ²dV: q = 0 gives A/Φ_G, q > 0 gives 2A/Φ_G. **`cabin_eps_3d` equals Eq. (C.11) as printed** (it was an interpretation only because an earlier scan could not be read; the page image is legible). The register row is updated accordingly.\n")

maxrel = 0.0; maxrel_ratio = 0.0
rows = String[]
for m in cy.modes[1:10]
    Iφ = area_integral_phi2(m)
    for q in 0:3
        eq = A_exact / (Iφ * zfac(q) / 1.0)       # V/∫φ²dV with V = A_exact·L, L = 1
        ec = cabin_eps_3d(m, q)
        rel = (eq - ec) / ec
        global maxrel = max(maxrel, abs(rel))
        push!(rows, @sprintf("| %d | %d | %.2f | %.5f | %.5f | %+.2f %% |", m.index, q, m.f_Hz_unit, ec, eq, 100rel))
    end
    # the q > 0 / q = 0 ratio: quadrature against the code's exact 2
    r_quad = (A_exact / (Iφ * zfac(1))) / (A_exact / (Iφ * zfac(0)))
    global maxrel_ratio = max(maxrel_ratio, abs(r_quad - 2))
end
println(io, "## Quadrature against `cabin_eps_3d`\n")
println(io, "| mode i | q | f_i (Hz, a = 1 m) | `cabin_eps_3d` | quadrature V/∫φ²dV | difference |\n|---:|---:|---:|---:|---:|---:|")
foreach(r -> println(io, r), rows)
# which differences are from the q = 0 normalization (C.10 sum against a quadrature) and which from q
qd = [abs((A_exact / (area_integral_phi2(m) * zfac(0))) / m.eps_n - 1) for m in cy.modes[1:10]]
println(io, "\n- Largest |difference|: **$(round(100maxrel; digits=2)) %** (criterion 0.5 %): **$(maxrel <= 0.005 ? "met" : "not met")**.")
println(io, "- Part from the q = 0 normalization alone (Eq. (C.10) node sum with C(j) weights against the Voronoi quadrature of the true cabin; the same sum NASA printed): up to $(round(100maximum(qd); digits=2)) % over the 10 modes. It is the same for every q.")
println(io, "- The q > 0 to q = 0 ratio: code exactly 2; quadrature within $(@sprintf("%.1e", maxrel_ratio)) of 2 (the ∫cos² dz = L/2 factor).")

# 18b effect of the alternative reading: ε_n(q > 0) = ε_n(q = 0)
paths = default_e11_paths()
tg = PAIN._read_csv_numeric(joinpath(dirname(paths.A), "t1_interior_targets.csv"))
nasa = tg[:nasa_pain_pred_dB]
run18b() = run_pain_pipeline(; source=:e11, e11_amp_csv=paths.anopp_spl, n_harmonics=3, bpf_Hz=200.0, blocking=R1, trim=:phase3).spectrum.harmonic_SPL_dB
s0 = run18b()
@eval PAIN cabin_eps_3d(mode::AcousticMode, q::Int) = mode.eps_n     # alternative reading, this process only
s1 = run18b()
println(io, "\n## 18b effect of the alternative reading ε_n(q > 0) = ε_n(q = 0) (diagnostic, not adopted)\n")
println(io, "Same 18b inputs (registered run: R1 blocking, Phase III trim, ANOPP Table 8 with GEXT off the ℓ = 1 line). The alternative is applied to every use of `cabin_eps_3d` (Eq. (8), Eq. (77) normalization, Eq. (83)). NASA PAIN predictions (Fig. E-16 circles): $(nasa[1]), $(nasa[2]), $(nasa[3]) dB.\n")
println(io, "| Reading | H1 dB | H2 dB | H3 dB | vs NASA (dB) |\n|---|---:|---:|---:|---|")
@printf(io, "| as printed (code) | %.2f | %.2f | %.2f | %+.1f, %+.1f, %+.1f |\n", s0..., (s0 .- nasa[1:3])...)
@printf(io, "| ε_n(q > 0) = ε_n(q = 0) | %.2f | %.2f | %.2f | %+.1f, %+.1f, %+.1f |\n", s1..., (s1 .- nasa[1:3])...)
@printf(io, "| shift | %+.2f | %+.2f | %+.2f | |\n", (s1 .- s0)...)
println(io, "\nThe alternative contradicts the printed ε_q (p. C-7) and Eq. (C.11); it is recorded to show whether this reading could explain the 18b miss. Criterion for the miss itself is unchanged (4 dB): $(count(abs.(s1 .- nasa[1:3]) .<= 4)) of 3 harmonics within 4 dB under the alternative.")
out = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "eps_n_quadrature.md")
write(out, String(take!(io))); println(read(out, String))
