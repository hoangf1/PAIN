#!/usr/bin/env julia
# Phase 78b (IMPLEMENTATION_PLAN.md §8v): isolation checks of the App. D structural solver (`src/mrp_appd.jl`),
# each part against an independent reference, none against Table D-1 frequencies. Diagnostic: no criterion, no
# code change. Writes docs/validation_reports/phase78_appd_isolation.md.
using PAIN
using LinearAlgebra
using Printf

const OUT = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "phase78_appd_isolation.md")

"""Independent Donnell 3×3 (in-plane inertia kept), simply supported closed cylinder (Leissa NASA SP-288 §2):
lowest root of det(L − Ω² I) = 0, Ω² = ρ(1−ν²)a²ω²/E, λ = mπa/L, k = t²/(12a²)."""
function donnell3_Hz(m, n, L, a, t, E, ν, ρ)
    λ = m * π * a / L; k = t^2 / (12a^2)
    A = [λ^2+(1-ν)/2*n^2      (1+ν)/2*λ*n       ν*λ;
         (1+ν)/2*λ*n          (1-ν)/2*λ^2+n^2   n;
         ν*λ                  n                 1+k*(λ^2+n^2)^2]
    Ω2 = minimum(eigvals(Symmetric(A)))
    return sqrt(Ω2 * E / (ρ * (1 - ν^2) * a^2)) / (2π)
end

function main()
    g = appd_test_article_geometry()
    L = String["# Phase 78b: App. D solver isolation checks (diagnostic, 2026-10-28)", "",
        "Generated by `scripts/checks/appd_isolation.jl`. Each part of `src/mrp_appd.jl` against an independent reference; " *
        "Table D-1 is used only in check 6, for its printed generalized masses and identities. No code was changed.", ""]

    # 1. bare cylinder
    bare = PAIN.AppDGeometry(g.L, g.a, g.theta0_deg, g.t_skin, g.t_floor, 0.0, g.d_stringer, 0.0, 0.0, g.ell_frame,
                             0.0, 0.0, 0.0, g.E, g.ν, g.ρ)
    push!(L, "## 1. Bare cylinder (no stiffeners, no floor): App. D shell harmonic vs independent Donnell 3×3", "",
          "| m | n | App. D [Hz] | Donnell 3×3 [Hz] | ratio |", "|---|---|---|---|---|")
    w1 = 0.0
    for (m, n) in ((1, 2), (1, 3), (1, 4), (1, 5), (2, 3), (2, 4), (3, 4), (1, 6))
        a = appd_shell_harmonic_frequency_Hz(m, n, bare)
        d = donnell3_Hz(m, n, g.L, g.a, g.t_skin, g.E, g.ν, g.ρ)
        w1 = max(w1, abs(a / d - 1))
        push!(L, @sprintf("| %d | %d | %.1f | %.1f | %.4f |", m, n, a, d, a / d))
    end
    push!(L, "", @sprintf("Largest |ratio − 1|: %.4f.", w1), "")

    # 2. floor plate alone (simply supported on all edges, same Df and mf): closed form
    fp = PAIN._appd_floor_props(g)
    push!(L, "## 2. Floor plate alone vs the simply supported plate closed form (same Df, mf)", "",
          "f = (π/2)·√(Df/mf)·((M/L)² + (p/Lp)²); the App. D floor block is the same Kirchhoff energy, so this checks its assembly.", "",
          "| M | p | App. D floor block [Hz] | closed form [Hz] |", "|---|---|---|---|")
    for (M, p) in ((1, 1), (1, 2), (2, 1), (1, 3))
        K, Ms = PAIN._appd_floor_harmonic_KM(M, p, g.L, fp, false)
        fa = sqrt(K[3, 3] / Ms[3, 3]) / (2π)
        fc = (π / 2) * sqrt(fp.Df / fp.mf) * ((M / g.L)^2 + (p / fp.Lp)^2)
        push!(L, @sprintf("| %d | %d | %.1f | %.1f |", M, p, fa, fc))
    end
    push!(L, "")

    # 3. smeared section properties: hand values from the App. E dimensions
    E = g.E; t = g.t_skin; ν = g.ν
    Dsk = E * t^3 / (12 * (1 - ν^2))
    Ich = 0.038^3 * 0.00081 / 12 + 2 * (0.017 * 0.00081) * (0.038 / 2)^2     # channel about its web centroid, flanges included
    push!(L, "## 3. Smeared section properties (App. E dimensions; independent hand values)", "",
          "| quantity | code | hand | note |", "|---|---|---|---|",
          @sprintf("| skin D [N·m] | %.3f | %.3f | E t³/12(1−ν²) |", PAIN._appd_kD(E, ν, t)[2], Dsk),
          @sprintf("| frame I [m⁴] | %.3e | %.3e | code: web only (0.038³·t/12); hand: channel with two 0.017 m flanges |", g.I_frame, Ich),
          @sprintf("| D_θR [N·m] | %.1f | %.1f | D_skin + E·I_frame/ℓ (hand with the channel I) |", PAIN._appd_shell_props(g).D_θR, Dsk + E * Ich / g.ell_frame),
          @sprintf("| floor Df [N·m] | %.1f | x: %.1f, y: %.1f | code: one isotropic sum; hand: longitudinal beams stiffen x, the per-frame supports y |",
                   fp.Df, Dsk + 2 * E * g.I_floor_beam / fp.Lp, Dsk + E * g.I_floor_beam / g.ell_frame), "")

    # 4. mass budget
    ρ = g.ρ; a = g.a; θ0 = deg2rad(g.theta0_deg); Lp = fp.Lp
    m_skin = ρ * t * 2π * a * g.L
    m_str = 18 * g.A_stringer * g.L * ρ
    m_fr = 8 * g.A_frame * 2π * a * ρ
    m_floor = ρ * t * Lp * g.L
    m_fb = 2 * g.A_floor_beam * 1.79 * ρ
    sp = PAIN._appd_shell_props(g)
    m_model = sp.ms * 2π * a * g.L + fp.mf * Lp * g.L
    push!(L, "## 4. Mass budget (App. E geometry, kg)", "",
          @sprintf("Skin %.2f, 18 stringers %.2f, 8 frames %.2f, floor plate %.2f, 2 floor beams %.2f: total %.2f. Model (smeared ms over the full circumference + mf over the floor): %.2f (ratio %.3f). Per-frame floor supports and end caps not included in either.",
                   m_skin, m_str, m_fr, m_floor, m_fb, m_skin + m_str + m_fr + m_floor + m_fb, m_model,
                   m_model / (m_skin + m_str + m_fr + m_floor + m_fb)), "")

    # 5. floor effect on the (m=1) family and the closed-cylinder spectrum
    md = appd_modes(g; n_modes=80, n_axial=7, n_circ=8, n_floor_max=5).modes
    push!(L, "## 5. Stiffened cylinder without floor vs the coupled model", "",
          "| (m, n) | closed stiffened cylinder [Hz] |", "|---|---|")
    for (m, n) in ((1, 2), (1, 3), (1, 4), (2, 4), (3, 4))
        push!(L, @sprintf("| (%d, %d) | %.1f |", m, n, appd_shell_harmonic_frequency_Hz(m, n, g)))
    end
    push!(L, "", @sprintf("Coupled model: lowest mode %.1f Hz; %d modes below 820 Hz (Table D-1: 32 up to 811 Hz).",
                          md[1].f_Hz, count(x -> x.f_Hz < 820, md)), "")

    # 6. generalized masses of the identity-matched modes against Table D-1's printed M_r
    _, pairs = match_modes_by_identity(StructuralModes(md, g.L, g.a, g.theta0_deg, ""))
    push!(L, "## 6. Identity-matched modes: frequency and generalized mass against Table D-1", "",
          "| D-1 mode | f D-1 [Hz] | f solver [Hz] | M_r D-1 [kg] | M_r solver [kg] |", "|---|---|---|---|---|")
    for p in pairs
        p.found || continue
        push!(L, @sprintf("| %d | %.1f | %.1f | %.3f | %.3f |", p.d1, p.ref, p.got, PAIN.TABLE_D1_FULL[p.d1][4], md[p.ritz].M_r))
    end
    write(OUT, join(L, "\n") * "\n")
    println("wrote ", OUT)
end

main()
