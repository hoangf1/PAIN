#!/usr/bin/env julia
# Phase 117 (diagnostic, 2026-11-02): which factor of Eq. (83) puts run 10's η_r″ near 0.6× NASA's printed ETA R# away
# from resonance (Phase 109). Tests fixed in IMPLEMENTATION_PLAN.md §8bg (commit 001b34f) before any factor was computed.
# Every variant lives in this process (no src/ change, no default changed, no verdict). Writes
# docs/validation_reports/phase117_run10_eta_rpp.md.
using Pkg; Pkg.activate(joinpath(@__DIR__, "..", ".."))
using PAIN, Printf, Statistics

const DATA = joinpath(@__DIR__, "..", "..", "..", "data", "cr172428")
function rows(name)
    ls = [l for l in eachline(joinpath(DATA, name)) if !startswith(l, "#")]
    hdr = Symbol.(split(ls[1], ","))
    return [Dict(zip(hdr, split(l, ","))) for l in ls[2:end]]
end
num(r, k) = parse(Float64, r[k]); int(r, k) = parse(Int, r[k])
io = IOBuffer()
p(args...) = println(io, args...)
f2(x) = @sprintf("%.2f", x); f3(x) = @sprintf("%.3f", x); e3(x) = @sprintf("%.3e", x)

inp = PAIN.r172428_flight10_inputs()                 # as it ships: floor sign −1 (Phase 108)
a, L, Lc = inp.fuse.a, inp.fuse.L, inp.L_c
θ0 = deg2rad(inp.fuse.theta0_deg)
per = 2a * sin(θ0) + 2a * (π - θ0)
A = L * per
V = PAIN.cabin_volume(inp)
bpf = PAIN.FLIGHT10_BPF_Hz

# H1 and H5 field rows are cut in the scan; η_r″ does not use the field (as Phase 108), so a zero field stands in
z = zeros(size(inp.amplitudes, 1), size(inp.amplitudes, 2), 1)
inp5 = PAIN._with_fields(inp; amplitudes=cat(inp.amplitudes, z; dims=3), phases=cat(inp.phases, z; dims=3))
terms = Dict{Int,Vector}()
for H in 1:5
    t = NamedTuple[]
    PAIN.tone_mean_square_pressure(inp5, H, 2π * bpf * H; terms=t)
    terms[H] = t
end

masses = Dict(int(r, :mode) => (; total=num(r, :M_total_kg), shell=num(r, :shell_W_kg), plate=num(r, :plate_W_kg),
                                  f=num(r, :f_Hz)) for r in rows("appC_merlin_structural_modes_checked.csv"))

recs = NamedTuple[]
for r in rows("appD_run10_pairs.csv")
    nasa = num(r, :eta_r_hash); nasa > 0 || continue
    H, q, I, sr = int(r, :H), int(r, :Q), int(r, :I), int(r, :st_mode)
    t = terms[H][findfirst(x -> x.q == q && x.i == I && x.r == sr, terms[H])]
    ac = PAIN._acmode_by_I(inp, I); st = inp.structural.modes[sr]
    ωn, ωr = 2π * t.f_n_Hz, 2π * t.f_r_Hz
    N = t.η_n * ωn^2
    s = N^2 / ((ωn^2 - ωr^2)^2 + N^2)
    fp = PAIN.coupling_factor(ac, st, inp; τ_t=1.0, q)
    ε = PAIN.cabin_eps_3d(ac, q)
    # the pair's η_r″ by Eq. (83) as written here, to check the factor table reproduces the code's term
    η_chk = PAIN.structural_loss_coupled(N, ωn, ωr, fp, ε, st.M_r, V, A; ρ0=inp.ρ_int, c0=inp.c_int)
    push!(recs, (; H, q, I, sr, nasa, ours=t.η_r_pp, ratio=t.η_r_pp / nasa, η_chk, f_n=t.f_n_Hz, f_r=t.f_r_Hz,
                 f_n_nasa=num(r, :f_n_Hz), f_r_nasa=num(r, :f_r_Hz), η_n=t.η_n, s, fp, ε, M=st.M_r,
                 printed=get(masses, sr, nothing)))
end

p("# Phase 117 — run 10's η_r″ at 0.6× NASA's away from resonance (diagnostic, 2026-11-02)\n")
p("Generated by `scripts/checks/diag_run10_eta_rpp.jl`. Tests fixed in `IMPLEMENTATION_PLAN.md` §8bg (commit 001b34f) ",
  "before any factor was computed. Diagnostic: every variant lives in the script's process (no `src/` change, no default ",
  "changed, no verdict). Run 10 as `r172428_flight10_inputs()` ships (Phases 104–108; floor sign −1). η_r″ does not use the ",
  "field, so H1 and H5 (cut in the scan) run on a zero field, as in Phase 108.\n")
p("Eq. (83), CR-3813 p. 43: η_r″ = ρc₀²A²ε_n f′²/(ω_n²M_rV) · η_n/[(1 − ω_r²/ω_n²)² + η_n²]. Here ρc₀² = ",
  "$(f2(inp.ρ_int * inp.c_int^2)) Pa (inside air), A = L·(L_p + 2a(π − θ₀)) = $(f2(A)) m², V = $(f2(V)) m³ (on L_c = $Lc m).\n")
p("Check: the factor table's own Eq. (83) evaluation equals the code's pair term at every pair (max relative difference ",
  e3(maximum(abs(r.η_chk / r.ours - 1) for r in recs)), ").\n")

p("## (a) Factor table, $(length(recs)) printed pairs with ETA R# > 0\n")
p("s = N²/[(ω_n² − ω_r²)² + N²] (1 at exact resonance). M_r here: this code's generalized mass; printed: App. C pp. 213–216 ",
  "(total / shell W / plate W; — where the scan cuts the mode).\n")
p("| H | Q, I × r | f_n / f_r (Hz) | NASA ETA R# | ours | ours/NASA | η_n | s | f′ | ε_n | M_r here (kg) | printed total / shell W / plate W (kg) |")
p("|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in recs
    pm = r.printed === nothing ? "—" : "$(f2(r.printed.total)) / $(f2(r.printed.shell)) / $(f2(r.printed.plate))"
    p("| $(r.H) | Q$(r.q) I$(r.I) × $(r.sr) | $(f2(r.f_n)) / $(f2(r.f_r)) | $(@sprintf("%.5f", r.nasa)) | $(@sprintf("%.5f", r.ours)) | ",
      "$(f2(r.ratio)) | $(@sprintf("%.4f", r.η_n)) | $(f3(r.s)) | $(@sprintf("%.4f", r.fp)) | $(f3(r.ε)) | $(f2(r.M)) | $pm |")
end
lr = log10.([r.ratio for r in recs])
p("\nRatio ours/NASA over the $(length(recs)) pairs: median $(f2(median([r.ratio for r in recs]))), geometric mean ",
  "$(f2(10^mean(lr))); in [0.8, 1.25]: $(count(r -> 0.8 ≤ r.ratio ≤ 1.25, recs)); in [0.4, 2.5]: $(count(r -> 0.4 ≤ r.ratio ≤ 2.5, recs)).\n")

p("## (b) H_M: the generalized mass\n")
withp = filter(r -> r.printed !== nothing, recs)
inb(x) = 0.8 ≤ x ≤ 1.25
base_in = count(r -> inb(r.ratio), withp)
p("Pairs whose structural mode is printed: $(length(withp)) of $(length(recs)). With this code's M_r: median ratio ",
  "$(f2(median([r.ratio for r in withp]))), $base_in in [0.8, 1.25].\n")
p("M_r here / printed total at those modes: median $(f3(median([r.M / r.printed.total for r in withp]))), range ",
  "$(f3(minimum(r.M / r.printed.total for r in withp)))–$(f3(maximum(r.M / r.printed.total for r in withp))).\n")
p("| printed mass in Eq. (83) | median ratio | pairs in [0.8, 1.25] (here: $base_in) | H_M |")
p("|---|---|---|---|")
hm = Dict{String,String}()
for (lab, g) in (("total", m -> m.total), ("shell W", m -> m.shell), ("plate W", m -> m.plate), ("shell W + plate W", m -> m.shell + m.plate))
    rr = [r.ratio * r.M / g(r.printed) for r in withp]
    k = count(inb, rr); med = median(rr)
    v = inb(med) && k ≥ base_in + 5 ? "supported" : "not supported"
    hm[lab] = v
    p("| $lab | $(f2(med)) | $k | $v |")
end

p("\n## (c) H_N: the cabin damping (ratio against the resonance share s)\n")
rank(x) = (o = sortperm(x); rk = similar(x); rk[o] = 1:length(x); rk)
ρs = cor(rank([r.s for r in recs]), rank([r.ratio for r in recs]))
hn = ρs ≥ 0.5 ? "H_N supported" : abs(ρs) < 0.3 ? "a pair-independent factor (H_N not supported)" : "undecided"
off = filter(r -> r.s < 0.1, recs); on = filter(r -> r.s ≥ 0.1, recs)
p("Spearman ρ(ratio, s) = $(f2(ρs)): **$hn**. Pairs with s < 0.1: $(length(off)), median ratio ",
  "$(isempty(off) ? "—" : f2(median([r.ratio for r in off]))); s ≥ 0.1: $(length(on)), median ratio ",
  "$(isempty(on) ? "—" : f2(median([r.ratio for r in on]))).\n")

p("## (d) Documented constant alternatives (the factor each puts on every pair; reported only)\n")
p("| alternative | factor on η_r″ | median ratio with it |")
p("|---|---|---|")
medr = median([r.ratio for r in recs])
for (lab, fac) in (("ρ_ext c_ext² for ρ_int c_int²", inp.ρ_ext * inp.c_ext^2 / (inp.ρ_int * inp.c_int^2)),
                   ("A on L_c instead of L", (Lc / L)^2),
                   ("V on L instead of L_c", Lc / L),
                   ("card 20's A_t = 28.10 m² for A", (28.10 / A)^2))
    p("| $lab | $(f3(fac)) | $(f2(medr * fac)) |")
end

p("\n## Reading\n")
p("H_M: ", join(["$k $v" for (k, v) in sort(collect(hm))], "; "), ". H_N (Spearman): $hn.\n")

# ---------------------------------------------------------------------------------------------------------------------
# (e) Post-hoc, formed after (a)–(d) were seen: f′ normalized over the part of the structure over the cavity
p("## (e) Post-hoc: f′ normalized over the cavity (read after (a)–(d); no verdict, nothing adopted)\n")
p("CR-3813's list of symbols (p. F-1) names two areas: A, \"cylinder surface area, used in Eq. (4)\", and A, \"interior ",
  "(cylinder & floor) surface area, used in conjunction with structural/acoustic coupling function f′(n,r)\". CR-3813 §3.5 ",
  "sends L ≠ L_c to Ref. [3] (CR-159363 Eqs. 23–25), which defines f′ = (1/A′)∫_{A′} φψ dx with A′ \"the transmitting area\" ",
  "and treats only L ≤ L_c (structure inside the cavity), where A′ is the structure. Run 10 is the only PAIN print here ",
  "with L > L_c (9.27 against 7.89 m, d = 0). This code divides the overlap integral by L (Phase 38f-1, no document cited). ",
  "If PAIN divides by the length over the cavity (its transmitting area) while forming A from the card-8 L, f′ is ",
  "L/L_c = $(f3(L / Lc)) larger at every run-10 pair, and Eqs. (8) and (83) both carry (L/L_c)² = $(f3((L / Lc)^2)); nothing ",
  "changes at L = L_c (App. B, CR-3813). Formed after the 0.65 was seen and with no held-out print (H1/H5 phase rows are ",
  "cut; no other L ≠ L_c run is printed), so it is a post-hoc candidate, not a finding.\n")
k2 = (L / Lc)^2
rr = [r.ratio * k2 for r in recs]
p("η_r″ ours/NASA with it: median $(f2(median(rr))), geometric mean $(f2(10^mean(log10.(rr)))); in [0.8, 1.25]: ",
  "$(count(inb, rr)) of $(length(rr)) (as shipped $(count(r -> inb(r.ratio), recs))).\n")

# process-local override: the overlap integral divided by the overlap length instead of L (variant only)
spl3(i) = PAIN.interior_spl(i; bpf_Hz=bpf, n_harmonics=4, broadband=false).harmonic_SPL_dB[2:4]
pairs_p2(i) = Dict(H => (t = NamedTuple[]; PAIN.tone_mean_square_pressure(i, H, 2π * bpf * H; terms=t); t) for H in 2:4)
lv0 = spl3(inp); pp0 = pairs_p2(inp)
@eval PAIN function axial_coupling(q::Int, M::Int; L::Real=1.0, L_c::Real=L, d::Real=0.0)
    Lf, Lcf, df = float(L), float(L_c), float(d)
    z0 = max(0.0, -df); z1 = min(Lf, -df + Lcf)
    z1 ≤ z0 && return 0.0
    return _axial_overlap_integral(q, M, Lf, Lcf, -df, z0, z1) / (z1 - z0)
end
lv1 = spl3(inp); pp1 = pairs_p2(inp)
nasa = PAIN.FLIGHT10_PAIN_dB[2:4]
p("Run 10 H2–H4 (dB re 20 μPa; PAIN App. D p. 237 $(nasa)):\n")
p("| tone | PAIN | as shipped | Δ | f′ over the cavity | Δ |")
p("|---|---|---|---|---|---|")
for i in 1:3
    p("| H$(i + 1) | $(f2(nasa[i])) | $(f2(lv0[i])) | $(f2(lv0[i] - nasa[i])) | $(f2(lv1[i])) | $(f2(lv1[i] - nasa[i])) |")
end
dp(pp) = [10log10(pp[int(r, :H)][findfirst(x -> x.q == int(r, :Q) && x.i == int(r, :I) && x.r == int(r, :st_mode), pp[int(r, :H)])].p2 /
                  num(r, :p2_Pa2)) for r in rows("appD_run10_pairs.csv") if int(r, :H) in 2:4]
d0, d1 = dp(pp0), dp(pp1)
p("\nNASA's 15 printed H2–H4 pair levels, this code − NASA (dB): as shipped median $(f2(median(d0))), within 3 dB ",
  "$(count(x -> abs(x) ≤ 3, d0))/15; f′ over the cavity median $(f2(median(d1))), within 3 dB $(count(x -> abs(x) ≤ 3, d1))/15.\n")
p("All of (e) is post-hoc (run 10's levels, pairs and η_r″ were seen in Phases 102–109): it shows what the reading would ",
  "do, not that PAIN does it. The default stays the 38f-1 normalization, which is consistent: A and f′ use the same ",
  "length L, so A·f′ is the overlap integral. The author kept it (Q99, 2026-11-02; `COMPLETED_PHASES.md` §3).\n")

out = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "phase117_run10_eta_rpp.md")
write(out, String(take!(io)))
println("wrote ", out)
