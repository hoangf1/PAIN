#!/usr/bin/env julia
# Plan 19h: η_r of Eqs. (79)-(81) and the normalization of j_r^rev, Eq. (66). Text read from the page images (CR-3813 pp. 38-39, 43);
# the alternative normalizations are run on the 18b inputs as diagnostics, not adopted. Criterion fixed 2026-10-20 before the run (IMPLEMENTATION_PLAN.md,
# phase 19): text quoted; the 18b shift of the normalized form recorded in dB, not adopted without confirmation. No `src/` change.
using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
include(joinpath(@__DIR__, "bisect_18b_chain.jl"))       # local tone sum with switches, the registered 18b inputs (inp0, inp05) and nasa
const Pk = PAIN
d1 = [split(l, ",") for l in readlines(joinpath(@__DIR__, "..", "..", "data", "digitized_table_D1.csv"))[2:end] if !isempty(strip(l))]
shellmass = Dict{Int,Float64}(); cur = 0
for r in d1
    if !isempty(r[1]); global cur = parse(Int, r[1]); shellmass[cur] = parse(Float64, r[11]); end
end
a, L, c0, ρ0 = inp0.fuse.a, inp0.fuse.L, inp0.c0, inp0.ρ0
function jr2(st, ω, variant)
    k = ω / c0
    if variant == :printed
        return Pk.structural_joint_acceptance(st, ω; a, L, c0)
    elseif variant == :doubled        # every n > 0 and the axial form doubled (each component normalized by its own mean square), weights C² unchanged
        return Pk.structural_joint_acceptance(st, ω; a, L, c0, mode_normalized=true)
    else                              # shell shape normalized by its own mean square: Σ C² j_n (printed) / Σ C² w_n, w_0 = 1, w_n = 1/2; axial doubled
        jM = Pk.axial_joint_acceptance(st.M_axial, k * L; mode_normalized=true)
        num = 0.0; den = 0.0
        for (C, n) in zip(st.C_shell, st.n_shell)
            if st.symmetric
                num += C^2 * Pk.ring_joint_acceptance(n, k * a, :psi); den += C^2 * (n == 0 ? 1.0 : 0.5)
            elseif n ≥ 1
                num += C^2 * Pk.ring_joint_acceptance(n, k * a, :phi); den += C^2 * 0.5
            end
        end
        return jM * num / den
    end
end
mass_factor(st) = shellmass[st.index] / st.M_r      # M_shell / M_r (Table D-1 SHELL W MASS over total mass)
function etar(st, ω, variant)
    j2 = jr2(st, ω, variant === :physical ? :shape : variant)
    rad = Pk.radiation_loss_factor(j2, ω; Abar=2π * a * L, m=inp0.m_wall, ρ0, c0) * (variant === :physical ? mass_factor(st) : 1.0)
    return Pk.structural_loss_vacuo(ω / 2π; C=inp0.C_struc) + rad
end
variants = [(:printed, "as printed, Eqs. (66)-(68), (81) (the code)"),
            (:doubled, "n > 0 and axial forms doubled (each component normalized by its mean square)"),
            (:shape, "shell shape normalized by its own mean square (Σ C² j_n / Σ C² w_n)"),
            (:physical, "as the previous row times M_shell/M_r (η_rad per generalized mass; derived here, not printed)")]
io2 = IOBuffer()
println(io2, "# η_r of Eqs. (79)-(81) and the normalization of j_r^rev (plan 19h)\n")
println(io2, "Generated by `scripts/check_eta_r_normalization.jl`. Criterion fixed 2026-10-20 before the run (`IMPLEMENTATION_PLAN.md`, phase 19): text quoted; the 18b shift of the normalized form recorded in dB, not adopted without confirmation. No `src/` change.\n")
println(io2, "## Text (CR-3813 pp. 38, 39, 43, read from the page images)\n")
println(io2, """
- p. 38: j_N²(ω, ψ) = ∫₀¹∫₀¹ [sin 2πka(y₁−y₂)/2πka(y₁−y₂)] cos 2Nπy₁ cos 2Nπy₂ dy₁dy₂, and the same with sines for φ; j_N^rev = j_N(ψ) + j_N(φ) = ∫∫ sinc · cos 2Nπ(y₁−y₂) dy₁dy₂ = 2∫₀¹ [sin 2πka η̄/2πka η̄](1−η̄) cos 2πNη̄ dη̄; j_0^rev = ∫₀¹ [sin 2πka η̄/2πka η̄](1−η̄)dη̄. **No normalization by the mode's mean square or by M_r appears in the definition.**
- p. 39, Eq. (66): "j_r^rev(ω) = j_M^rev(ω) · j_N^rev(ω)", Eq. (67) symmetric: j_N^rev = Σ_{n=0}^∞ (C_Mn^sr)² j_n²(ω, ψ); Eq. (68) antisymmetric: Σ_{n=1}^∞ (C_Mn^sr)² j_n²(ω, φ). "N is a counter ... for each r there is an M and a sequence of C_Mn^sr that are identified with index N." j_r^rev is built from the shell coefficients C_Mn^sr only; **no M_r and no ΣC² normalization is printed.**
- p. D-10: the coefficients are normalized so that the maximum normal displacement on plate or shell is 1.0 (not a mean-square normalization).
- p. 43, Eqs. (80), (81): η_r^struc = C/f_r (C between 2 and 4); η_r^rad = 2ρ0ωĀ/(πmc0) j_r^rev(ω_r), where j_r^rev is "given by Eq. (66)".

**Decision (text):** j_r^rev is used exactly as printed: the unnormalized C_Mn² sum, no division by M_r or by the mode's mean square. This is what the code does. The printed form is therefore not invariant under a rescaling of the mode shape (the 17i finding); that is a property of the printed equation (the maximum-1.0 normalization of p. D-10 fixes the scale). Whether NASA's program also multiplied by a mean-square factor is not stated and cannot be decided from the text. For a floor-dominated mode the shell coefficients are small (mode 1: shell mass 0.028 kg of 1.139 kg), so the printed η_r^rad is small there.
""")
println(io2, "## 18b with the alternatives (diagnostics, not adopted)\n")
println(io2, "NASA PAIN predictions: $(nasa[1]), $(nasa[2]), $(nasa[3]) dB. Same local tone sum as 19f (equal to PAIN's at the base setting).\n")
println(io2, "| η_r^rad normalization | trim η_T | H1 dB | H2 dB | H3 dB | shift vs printed (dB) | vs NASA (dB) |\n|---|---:|---:|---:|---:|---|---|")
for (inp, lab) in ((inp0, "0.05 (18b registered)"), (inp05, "0.5 (NASA's, 19e)"))
    sb = spl(inp, Opt())
    for (v, vl) in variants
        s = v === :printed ? sb : spl(inp, Opt(eta_r_tot=(st, ω) -> etar(st, ω, v)))
        @printf(io2, "| %s | %s | %.2f | %.2f | %.2f | %+.2f, %+.2f, %+.2f | %+.1f, %+.1f, %+.1f |\n", vl, lab, s..., (s .- sb)..., (s .- nasa)...)
    end
end
println(io2, "\nη_r^struc = C/f_r with C = 3 (register g) is the same in all rows. With the registered η_T = 0.05 the alternatives move H1 and H2 by at most 1.4 dB and H3 by at most 5.6 dB, small against the +12.9, +4.5, +16.9 dB miss. With NASA's η_T = 0.5 (19e) the shell-shape normalization brings the three harmonics to +2.4, -1.3, +3.9 dB; that row combines NASA's stated trim input with a normalization that is NOT printed (Eqs. 66-68 give the unnormalized sum), so it is a pointer for the author's decision, not a reproduction.")
out = joinpath(@__DIR__, "..", "..", "docs", "validation_reports", "eta_r_normalization.md")
