#!/usr/bin/env julia
# Plan 18b and 18b-r: PAIN reproduction check against NASA's own predictions (Fig. E-16 circles).
# 18b: criterion dated 2026-10-20 in VALIDATION_GUIDELINE.md §2.11.4, written before the first run, with the Phase III trim loss factor 0.05
#      (a register default, not NASA's value): recorded as "not met, wrong η_T".
# 18b-r: input correction (η_T = 0.5, CR-3813 p. E-24, the `phase3_trim` default since 2026-10-20), criterion unchanged (4 dB) and dated in
#      §2.11.5 before the run; the result was known from 19f, so it is not a blind test. A miss is a finding, not a reason to tune.
using Pkg; Pkg.activate(joinpath(@__DIR__, ".."))
using PAIN, Printf
paths = default_e11_paths()
tg = PAIN._read_csv_numeric(joinpath(dirname(paths.A), "t1_interior_targets.csv"))
nasa = tg[:nasa_pain_pred_dB]
io = IOBuffer()
println(io, "# PAIN reproduction check against NASA's predictions, Fig. E-16 (plan 18b and 18b-r, V-CODE)\n")
println(io, "Re-recorded 2026-10-21 after the amplitude-convention fix (I-17; sources cited); result known in advance in direction, therefore post-hoc.\n")
println(io, "Generated by `scripts/run_pain_reproduction.jl`. Criterion fixed 2026-10-20 before the run (`VALIDATION_GUIDELINE.md` §2.11.4, §2.11.5): |computed − NASA PAIN| ≤ 2 dB (digitization) + 2 dB = 4 dB at each harmonic. Conditional on GEXT on ANOPP Table 8 (no full-grid ANOPP output exists, 17j; V-ASSUMED).\n")
println(io, "**18b-r is an input correction with the result known from 19f (`bisect_18b.md`), not a blind test.** The original 18b (η_T = 0.05, a register default that is not NASA's value) stays in the record as \"not met, wrong η_T\". NASA's η_T = 0.5 is from CR-3813 p. E-24.\n")
println(io, "| Run | η_T | H1 dB | H2 dB | H3 dB | per-harmonic result (margin to the 4 dB limit) |\n|---|---:|---:|---:|---:|---|")
function res(s)
    parts = String[]
    for H in 1:3
        d = s[H] - nasa[H]
        m = 4.0 - abs(d)
        push!(parts, m >= 0 ? (m < 1.0 ? "within the criterion, margin $(round(m; digits=1)) dB ($(round(d; digits=1)) dB)" :
                                           "PASS, margin $(round(m; digits=1)) dB ($(round(d; digits=1)) dB)") :
                               "FAIL ($(round(d; digits=1)) dB)")
    end
    return join(parts, "; ")
end
function row(label, ηT; kw...)
    p3 = phase3_trim(; η_lining=ηT)          # the whole trim is rebuilt with η_T (facings, septum, mechanical path)
    r = run_pain_pipeline(; source=:e11, e11_amp_csv=paths.anopp_spl, n_harmonics=3, bpf_Hz=200.0, kw...,
                          sidewall_trim_stack=p3.sidewall, end_trim_stack=p3.ends, mech=p3.mech)
    s = r.spectrum.harmonic_SPL_dB
    ok = [abs(s[H] - nasa[H]) ≤ 4.0 for H in 1:3]
    @printf(io, "| %s | %.2f | %.2f | %.2f | %.2f | %s |\n", label, ηT, s[1], s[2], s[3], res(s))
    return ok
end
ok0 = row("18b original, R1, Phase III trim (**not met, wrong η_T**)", 0.05; blocking=R1)
okr = row("**18b-r: R1, Phase III trim, η_T = NASA's 0.5**", 0.5; blocking=R1)
println(io, "| NASA PAIN (Fig. E-16 circles) | | $(nasa[1]) | $(nasa[2]) | $(nasa[3]) | target |")
println(io, "\nDiagnostics (not the criterion, η_T = 0.5; for localizing a miss):\n\n| Run | η_T | H1 dB | H2 dB | H3 dB | per-harmonic result (margin to the 4 dB limit) |\n|---|---:|---:|---:|---:|---|")
row("R2 blocking, Phase III trim", 0.5; blocking=R2)
r = run_pain_pipeline(; source=:e11, e11_amp_csv=paths.anopp_spl, n_harmonics=3, bpf_Hz=200.0, blocking=R1, trim=:bare)
let s = r.spectrum.harmonic_SPL_dB
    @printf(io, "| R1, bare cabin, η_n = 0.05 | | %.2f | %.2f | %.2f | %s |\n", s[1], s[2], s[3], res(s))
end
println(io, "\nOriginal 18b (η_T = 0.05): criterion **not met** ($(count(ok0)) of 3). 18b-r (η_T = 0.5): criterion **$(all(okr) ? "met" : "not met")** ($(count(okr)) of 3 harmonics).")
println(io, "\nThe 18b-r result is not a clean reproduction: a harmonic inside the limit by less than 1 dB is reported as \"within the criterion\" with its margin. H3 stays an open finding (plan step 19i).")
out = joinpath(@__DIR__, "..", "..", "docs", "validation_reports", "pain_reproduction_e16.md")
write(out, String(take!(io))); println(read(out, String))
