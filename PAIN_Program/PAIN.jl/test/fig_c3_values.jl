"""Mismatches (mode, n, m, printed, computed) between the one-decimal Fig. C-3 values and a CYL2D result (global sign free)."""
function fig_c3_mismatches(cy)
    out = Tuple[]
    for (k, rows) in enumerate(FIG_C3_ROWS)
        m = cy.modes[k]
        errs = [Tuple[] , Tuple[]]
        for (si, s) in enumerate((1.0, -1.0))
            for (r, row) in enumerate(rows), (j, v) in enumerate(row)
                n = 11 - r          # first row is the crown n = 10
                got = s * m.phi_nodes[(j - 1, n)]
                round(got; digits=1) == v || push!(errs[si], (k - 1, n, j - 1, v, round(got; digits=3)))
            end
        end
        append!(out, length(errs[1]) <= length(errs[2]) ? errs[1] : errs[2])
    end
    return out
end
