# Phase 155 (2026-11-15): FLIGHT10_REPRO, run 10 H1–H5 for both propellers against PAIN's printed levels (App. D, Table 23).
# Phase 102 — CR-172428 flight-test run 10 (Merlin IVC), harmonics 2–4, from PAIN's printed deck and field
# (COMPLETED_PHASES.md §8ar; what is compared fixed 2026-10-30 before the run). Diagnostic: FLIGHT_MODES (Phase 101a)
# is not met, so this run carries no verdict. It sets the code as it ships and the trim per band against PAIN's
# printed levels.

const _P102_REPORT = "phase102_flight_run10_h234.md"

"""PAIN's printed run 10 levels, App. D p. 237 (dB re 20 μPa), H1–H5."""
const FLIGHT10_PAIN_dB = [99.90, 96.59, 88.06, 83.92, 71.02]

const FLIGHT10_BPF_Hz = 1568.0 * 4 / 60

"""
    r172428_flight10_field(; sweep=1) -> (; amps, phases, pts)

Run 10's field on the 16 × 19 grid (App. D pp. 230–234, H1–H5; H1 and H5 since Phase 155a, their phase rows cut in the
scan generated by PAIN's lower-quarter rule, `appD_run10_H1.csv`). θ as printed, from the bottom centreline:
−15° + 10°(L − 1), propeller line 75° at L = 10 (Phase 104: the deck's ℓ = 1…10 are grid lines L = 10…19, CR-172428
App. A item 5, the "upper quarter" of User Manual card 37; Phase 102 used 180° − θ, which put the propeller 15° above the
horizontal instead of 15° below).

`sweep = −1` gives the blade-upsweep field PAIN builds from the downsweep input (CR-172428 App. A item 5: `PMH(K, L+9)` and
`PMH(K, 11−L)` swapped when the sweep card is −1). The printed amplitudes are already mirror-symmetric, so the swap moves the
phase too: every value at L goes to 20 − L (Phase 155b; checked against Table 23's printed upsweep levels, FLIGHT10_REPRO).
"""
function r172428_flight10_field(; sweep::Integer=1)
    abs(sweep) == 1 || error("sweep must be +1 (downsweep) or −1 (upsweep)")
    amps = zeros(16, 19, 5); phases = zeros(16, 19, 5); zs = zeros(16)
    for H in 1:5
        c = _read_csv_numeric_nan(_r172428_csv("appD_run10_H$(H).csv"))
        for i in eachindex(c[:L])
            L, k = Int(c[:L][i]), Int(c[:k][i])
            zs[k] = c[:z_m][i]
            amps[k, L, H] = spl_dB_to_peak_Pa(c[:amp_dB][i])
            phases[k, L, H] = deg2rad(c[:phase_deg][i])
        end
    end
    if sweep == -1
        amps = amps[:, 20 .- (1:19), :]; phases = phases[:, 20 .- (1:19), :]
    end
    pts = [(; k, ell=L, x1=NaN, x2=NaN, x3=1.12 - zs[k], theta_deg=-15.0 + 10.0 * (L - 1),
             alpha_deg=abs(-15.0 + 10.0 * (L - 1) - 75.0), z=zs[k]) for k in 1:16 for L in 1:19]
    return (; amps, phases, pts)
end

"""
    r172428_flight10_inputs(; trim_band_centre=false, floor_sign=-1.0) -> PainInputs

Run 10 from PAIN's printed deck (App. D p. 229): ρ, c outside 1.1012, 334.08 and inside 1.204, 343.0; L = 9.27 m,
a = 0.84 m, L_c = 7.89 m, θ₀ = 50°; bare η_r = 2/f per band; acoustic loss factors from the trim; sidewall trim
0.055 m PF-105 (App. D table) + 1.95 kg/m², η_T = 2.0; no end-cap trim. Structural modes: the App. D solver on NASA's
Merlin deck (lowest 400; NASA kept 20 per axial order and symmetry, which differs only near the top of the list).
Acoustic modes: CYL2D at θ₀ = 50°, 20 two-dimensional modes, on NASA's printed Merlin grid: NY = 11 with the node rule
0.45h, which reproduces CR-172428 App. C p. 212 (ε(0,0) and all printed types; Phase 103). Chosen from that print for this
diagnostic run only (Phase 105, post-hoc; the default node rule 0.4h is unchanged). Shell mass 4.54 kg/m² (the deck).
The Eq. (52) floor term enters with the pre-correction sign (`floor_sign = −1`): run 10's printed η_r″ follow it
(Phase 103; held-out H1/H5 pairs 8/10 against 5/10, Phase 108), so NASA computed run 10 before CR-172428 App. A item 2.
"""
function r172428_flight10_inputs(; trim_band_centre::Bool=false, floor_sign::Real=-1.0, sweep::Integer=1)
    fuse = FuselageGeometry(9.27, 0.84, 50.0)
    prop = PropellerPlacement(2.35, 75.0, 1.12)        # card 36: 75° from the bottom vertical (Phase 104)
    f = r172428_flight10_field(; sweep)                # sweep −1: the upsweep side (Phase 155b)
    side = TrimStack(TrimElement[InsulationLayer(0.055, pf105_deck_table()), LimpMass(1.95, 2.0)], "Merlin IVC sidewall trim")
    ends = TrimStack(TrimElement[InsulationLayer(0.0, pf105_deck_table()), LimpMass(0.0, 1.0)], "no end-cap trim")
    structural = appd_modes(merlin_mrp_deck(); n_modes=400, n_axial=10, n_circ=14, n_floor_max=5)
    acoustic = cyl2d_modes(fuse.theta0_deg; n_modes=20, NY=11, c0=343.0, node_tol=0.45)   # NASA's printed Merlin grid
    η_r_band = Dict(fc => 2 / fc for fc in third_octave_centers())
    return PainInputs(fuse, prop, structural, acoustic, f.amps, f.phases, f.pts, (π * fuse.a / 18)^2;
                      sidewall=side, endplates=ends, mech=nothing, m_wall=4.54, L_c=7.89,
                      ρ_ext=1.1012, c_ext=334.08, ρ_int=1.204, c_int=343.0, η_r_band, trim_band_centre,
                      allow_extrapolation=true,   # mode 1 (39.6 Hz) is below the 50 Hz table start (X-EXTRAP)
                      floor_sign)                 # NASA's run 10 predates App. A item 2 (Phase 108, held-out H1/H5 pairs)
end

"""H2–H4 levels of run 10: (a) as shipped, (b) with the trim per band."""
function _run_flight10_h234()
    spl(inp) = interior_spl(inp; bpf_Hz=FLIGHT10_BPF_Hz, n_harmonics=4, broadband=false).harmonic_SPL_dB[2:4]
    a = spl(r172428_flight10_inputs()); b = spl(r172428_flight10_inputs(; trim_band_centre=true))
    nasa = FLIGHT10_PAIN_dB[2:4]; fz = FLIGHT10_BPF_Hz .* (2:4)
    table = ValidationTableRow[]
    for i in 1:3
        push!(table, ValidationTableRow("H$(i + 1) as shipped (dB re 20 μPa)", fz[i], nasa[i], a[i], a[i] - nasa[i], abs(a[i] - nasa[i]) ≤ 3.0, "as shipped"))
        push!(table, ValidationTableRow("H$(i + 1) trim per band (dB re 20 μPa)", fz[i], nasa[i], b[i], b[i] - nasa[i], abs(b[i] - nasa[i]) ≤ 3.0, "trim per band"))
    end
    closer = count(i -> abs(b[i] - nasa[i]) < abs(a[i] - nasa[i]), 1:3)
    series = [PlotSeries("PAIN, App. D p. 237", :reference_points, collect(fz), nasa; panel=1),
              PlotSeries("this code as it ships", :computed_points, collect(fz), a; panel=1),
              PlotSeries("trim per band (option)", :computed_points, collect(fz), b; panel=1)]
    r2 = x -> round.(x; digits=2)
    return ValidationCaseResult("FLIGHT10_H234", _today_iso(),
        (; criterion="none (diagnostic of the trim per band; FLIGHT_MODES met since Phase 142, the reproduction is FLIGHT10_REPRO)",
         date="2026-10-30", as_shipped=r2(a), band=r2(b), nasa, closer),
        table, series, :no_verdict,
        "diagnostic (no verdict): H2–H4 as shipped $(r2(a)) dB, trim per band $(r2(b)) dB, PAIN $(nasa) dB; the trim per band " *
        "is closer at $closer/3 (H_bandtrim $(closer ≥ 2 ? "supported" : "not supported") in the diagnostic)",
        "V-CODE (diagnostic)", joinpath(_VAL_REPORT_DIR, _P102_REPORT))
end

"""CR-172428 Table 23: PAIN's run 10–12 cabin levels (downsweep, upsweep, both) and the measured space average."""
function r172428_table23()
    rows = [split(l, ",") for l in eachline(_r172428_csv("table23_flight_levels.csv")) if !startswith(l, "#")][2:end]
    num(s) = s == "-" ? NaN : parse(Float64, s)
    return [(; run=parse(Int, r[1]), H=parse(Int, r[2]), f_Hz=num(r[3]), down=num(r[4]), up=num(r[5]), both=num(r[6]),
             measured=num(r[7])) for r in rows]
end

"""Power sum of two levels in dB."""
_dB_sum(a, b) = 10log10(10^(a / 10) + 10^(b / 10))

"""
Run 10, H1–H5, from PAIN's printed deck and field against PAIN's printed space-average levels (Phase 155; criterion fixed
2026-11-15 before any H1, H5 or upsweep run): downsweep vs App. D p. 237, upsweep and both sides vs Table 23; ±3 dB per
row, met if at least 4 of 5 rows are within it in each form. Downsweep H2–H4 are post-hoc (seen since Phase 102).
"""
function _run_flight10_repro()
    spl(inp) = interior_spl(inp; bpf_Hz=FLIGHT10_BPF_Hz, n_harmonics=5, broadband=false).harmonic_SPL_dB[1:5]
    down = spl(r172428_flight10_inputs()); up = spl(r172428_flight10_inputs(; sweep=-1)); both = _dB_sum.(down, up)
    t23 = sort([r for r in r172428_table23() if r.run == 10]; by=r -> r.H)
    ref = (; down=FLIGHT10_PAIN_dB, up=[r.up for r in t23], both=[r.both for r in t23])
    fz = FLIGHT10_BPF_Hz .* (1:5)
    table = ValidationTableRow[]; counts = Dict{String,Int}()
    for (name, got, nasa, src) in (("downsweep", down, ref.down, "App. D p. 237"), ("upsweep", up, ref.up, "Table 23"),
                                   ("both sides", both, ref.both, "Table 23"))
        for H in 1:5
            ok = abs(got[H] - nasa[H]) ≤ 3.0; counts[name] = get(counts, name, 0) + ok
            push!(table, ValidationTableRow("H$H $name, PAIN from $src (dB re 20 μPa)", fz[H], nasa[H], got[H], got[H] - nasa[H], ok, name))
        end
    end
    met = all(v -> v ≥ 4, values(counts))
    series = [PlotSeries("PAIN, both sides (Table 23)", :reference_points, collect(fz), ref.both; panel=1),
              PlotSeries("this code, both sides", :computed_points, collect(fz), both; panel=1),
              PlotSeries("PAIN, downsweep (App. D)", :reference_points, collect(fz), ref.down; panel=2),
              PlotSeries("this code, downsweep", :computed_points, collect(fz), down; panel=2),
              PlotSeries("PAIN, upsweep (Table 23)", :reference_points, collect(fz), ref.up; panel=3),
              PlotSeries("this code, upsweep", :computed_points, collect(fz), up; panel=3)]
    r2 = x -> round.(x; digits=2)
    return ValidationCaseResult("FLIGHT10_REPRO", _today_iso(),
        (; criterion="±3 dB of PAIN's printed level per row; met if ≥ 4 of 5 rows in each of downsweep, upsweep and both sides",
         date="2026-11-15", down=r2(down), up=r2(up), both=r2(both), counts=Dict(counts)),
        table, series, met ? :met : :not_met,
        "downsweep $(counts["downsweep"])/5, upsweep $(counts["upsweep"])/5, both sides $(counts["both sides"])/5 within ±3 dB " *
        "of PAIN's printed levels (criterion: ≥ 4 of 5 in each); downsweep H2–H4 post-hoc, the other rows held out",
        "V-CODE", joinpath(_VAL_REPORT_DIR, "phase155_merlin_flight.md"))
end

