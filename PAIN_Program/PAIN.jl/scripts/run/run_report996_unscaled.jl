#!/usr/bin/env julia
# Phase 141c (2026-11-10; the second-line form of ISSUE-029, decided by Claude under the author's delegation): the Report
# 996 sound levels of Figs. 12, 13(a) and 14 on the CCBlade loads as computed, not scaled to the measured thrust and
# torque. Written to data/report996/f1a_results_unscaled.csv; R996_FIG12, R996_FIG13A and R996_FIG14 draw it as a second
# line with no verdict. f1a_results.csv (the scaled, recorded run) is not touched.
include(joinpath(@__DIR__, "run_report996_acoustics.jl"))   # functions only; its main() runs only as a script

const OUT_UNSCALED = joinpath(DATA, "f1a_results_unscaled.csv")

function match_meas(dig, fig, Mt, xd, mB)
    for d in dig
        d.figure == fig && d.in_scope || continue
        fig == 14 && !(abs(d.M_t - Mt) < 0.02 && d.mB == mB) && continue
        fig == 13 && abs(d.x_over_D - xd) ≥ 0.05 && continue
        fig == 12 && !(abs(d.M_t - Mt) < 0.02 && abs(d.x_over_D - xd) < 0.03 && d.mB == mB) && continue
        return d.value
    end
    return NaN
end

function main_unscaled()
    af, _ = load_polar_set(POLAR; set=:primary, cr75=0.1251)
    dig = load_digitized()
    rows = []
    for Mt in (0.45, 0.60, 0.75, 0.90)                                    # Fig. 14 (as the scaled run)
        cfg = make_cfg(; beta75=10.0, Mt=Mt, B=2); R = cfg.propeller.tip_radius_m
        obs = hub_observers(R, 2R; x_over_D=[-0.125], d_over_D=0.083, x_sign=R996_X_SIGN)
        src = evaluate_propeller_source(cfg, obs; n_harmonics=8, num_src_times=64, af=af, allow_static=true)
        for (H, mB) in ((1, 2), (2, 4), (3, 6))
            meas = match_meas(dig, 14, Mt, -0.125, mB); A = src.amplitude[1, H]
            push_result!(rows; figure="fig14", case="beta10_B2_Mt$(Mt)", polar_set="primary", loads="ccblade_unscaled",
                x_over_D=-0.125, d_over_D=0.083, harmonic=mB, A_Pa=A, phase_rad=src.phase[1, H], p_rms=NaN, p_c=NaN,
                meas=meas, residual_pct=isnan(meas) ? NaN : 100 * (pa_to_dyne_cm2(A / sqrt(2)) - meas) / meas)
        end
    end
    xDs = [-0.5, -0.25, -0.125, 0.0, 0.125, 0.25, 0.5]                    # Fig. 13(a)
    cfg = make_cfg(; beta75=15.0, Mt=0.75, B=2); R = cfg.propeller.tip_radius_m
    obs = hub_observers(R, 2R; x_over_D=xDs, d_over_D=0.083, x_sign=R996_X_SIGN)
    src = evaluate_propeller_source(cfg, obs; n_harmonics=4, num_src_times=64, af=af, allow_static=true)
    for (i, xd) in enumerate(xDs)
        meas = match_meas(dig, 13, 0.75, xd, 2); A = src.amplitude[i, 1]
        push_result!(rows; figure="fig13a", case="beta15_Mt075", polar_set="primary", loads="ccblade_unscaled",
            x_over_D=xd, d_over_D=0.083, harmonic=2, A_Pa=A, phase_rad=src.phase[i, 1], p_rms=NaN, p_c=NaN,
            meas=meas, residual_pct=isnan(meas) ? NaN : 100 * (pa_to_dyne_cm2(A / sqrt(2)) - meas) / meas)
    end
    xDs12 = [-0.25, -0.125, 0.0, 0.125, 0.25]                             # Fig. 12(a)(b)
    for (Mt, ftag) in ((0.75, "fig12a"), (0.90, "fig12b"))
        cfg = make_cfg(; beta75=10.0, Mt=Mt, B=2); R = cfg.propeller.tip_radius_m
        obs = hub_observers(R, 2R; x_over_D=xDs12, d_over_D=0.083, x_sign=R996_X_SIGN)
        src = evaluate_propeller_source(cfg, obs; n_harmonics=8, num_src_times=64, af=af, allow_static=true)
        for (i, xd) in enumerate(xDs12), (H, mB) in ((1, 2), (2, 4), (3, 6), (4, 8))
            meas = match_meas(dig, 12, Mt, xd, mB); A = src.amplitude[i, H]
            push_result!(rows; figure=ftag, case="beta10_Mt$(Mt)", polar_set="primary", loads="ccblade_unscaled",
                x_over_D=xd, d_over_D=0.083, harmonic=mB, A_Pa=A, phase_rad=src.phase[i, H], p_rms=NaN, p_c=NaN,
                meas=meas, residual_pct=isnan(meas) ? NaN : 100 * (pa_to_dyne_cm2(A / sqrt(2)) - meas) / meas)
        end
    end
    open(OUT_UNSCALED, "w") do io
        println(io, "# Phase 141c (2026-11-10): Report 996 Figs. 12, 13(a), 14 on CCBlade loads not scaled to the measured thrust ",
                "and torque (primary polar set); generated by scripts/run/run_report996_unscaled.jl. No verdict: a second line.")
        println(io, "figure,case,polar_set,loads,x_over_D,d_over_D,harmonic,A_Pa,A_rms_Pa,phase_rad,p_rms_total_Pa,p_c,meas_dyne_cm2,residual_pct")
        for r in rows
            println(io, join([r.figure, r.case, r.polar_set, r.loads, r.x_over_D, r.d_over_D, r.harmonic, r.A_Pa, r.A_rms_Pa,
                              r.phase_rad, r.p_rms_total_Pa, r.p_c, r.meas_dyne_cm2, r.residual_pct], ','))
        end
    end
    println("wrote ", OUT_UNSCALED, " rows=", length(rows))
end

main_unscaled()
