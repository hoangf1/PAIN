# Phase 118c (2026-11-02): E14_LOSS on NASA's per-band PF-105 table (CR-172428 App. D deck) in place of Fig. A-2's six
# digitized frequencies. Diagnostic, no verdict; the run's form and the support rule were fixed in IMPLEMENTATION_PLAN.md
# §8bh before this script was run. Writes docs/validation_reports/phase118_e14_deck.md.
#   julia --project=. scripts/checks/diag_e14_deck.jl
using PAIN

const OUT = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "phase118_e14_deck.md")

base = PAIN._run_e14_loss()
deck = PAIN._run_e14_loss(; material=PAIN.pf105_deck_table())
nb, nd = count(r -> r.within_tolerance, base.table), count(r -> r.within_tolerance, deck.table)
n = length(base.table)
supported = nd ≥ nb + 4
f3(x) = string(round(x; digits=4))
pct(r) = string(round(100 * (r.computed / r.reference - 1); digits=1))

io = IOBuffer()
println(io, "# Phase 118c — E14_LOSS on NASA's per-band PF-105 table (diagnostic, 2026-11-02)\n")
println(io, "Generated by `scripts/checks/diag_e14_deck.jl`. Form and support rule fixed in `IMPLEMENTATION_PLAN.md` §8bh ",
        "before the run. E14_LOSS's computation (Eq. 78 band average with the Phase III trim, η_T = 0.5) with the insulation ",
        "table swapped: Fig. A-2's six digitized frequencies (`pf105_table`, as E14_LOSS ships) against NASA's per-band ",
        "PF-105 input (CR-172428 App. D deck, 21 bands, λ at 1600 Hz kept as printed; `pf105_deck_table`). Criterion ",
        "unchanged: ±25 % of NASA's calculated η_T = 0.5 curve (Fig. E-14) at all $n bands. No verdict, no default changed.\n")
println(io, "| band (Hz) | NASA η̄ (η_T = 0.5) | Fig. A-2 table | Δ % | ok | App. D deck table | Δ % | ok |")
println(io, "|---|---|---|---|---|---|---|---|")
for (b, d) in zip(base.table, deck.table)
    println(io, "| ", round(Int, b.x), " | ", f3(b.reference), " | ", f3(b.computed), " | ", pct(b), " | ",
            b.within_tolerance ? "yes" : "no", " | ", f3(d.computed), " | ", pct(d), " | ", d.within_tolerance ? "yes" : "no", " |")
end
println(io, "\nWithin ±25 %: Fig. A-2 table $nb/$n (E14_LOSS as recorded), App. D deck table $nd/$n. Support rule: at ",
        "least 4 more bands than $nb. **The cause is ", supported ? "supported" : "not supported", "**",
        supported ? "; E14_LOSS's input is not changed here (the deck is CR-172428's input, not CR-3813's)." :
                    ": the coarse digitization of Fig. A-2 does not explain E14_LOSS's miss.")
write(OUT, replace(String(take!(io)), "\n" => "\r\n"))
println("E14 deck: ", nb, "/", n, " -> ", nd, "/", n, " supported=", supported, "; wrote ", normpath(OUT))
