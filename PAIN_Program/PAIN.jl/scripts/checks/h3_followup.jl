#!/usr/bin/env julia
# Plan step 19i: H3 follow-up after the η_T correction. Criteria fixed 2026-10-20 before the run (IMPLEMENTATION_PLAN.md, step 19i):
# A: modal breakdown at η_T = 0.5 (no pass mark); B: omitted Table D-1 terms, one extra plate or shell term of size δ = ±0.057 for each of the
# four modes of part A at H3; implicated if it moves H3 by >= 3 dB toward NASA's 68.0 dB. Nothing is tuned or adopted; no `src/` change.
using Pkg; Pkg.activate(joinpath(@__DIR__, "..", ".."))
using PAIN, Printf
paths = default_e11_paths()
tg = PAIN._read_csv_numeric(joinpath(dirname(paths.A), "t1_interior_targets.csv"))
nasa = tg[:nasa_pain_pred_dB][1:3]
r = run_pain_pipeline(; source=:e11, e11_amp_csv=paths.anopp_spl, n_harmonics=3, bpf_Hz=200.0, blocking=R1, trim=:phase3)   # 18b-r inputs
inp = r.inputs
function with_modes(ms)
    PainInputs(inp.fuse, inp.prop, StructuralModes(ms, inp.structural.L, inp.structural.a, inp.structural.theta0_deg, ""),
               inp.acoustic, inp.amplitudes, inp.phases, inp.pts, inp.ΔA; sidewall=inp.sidewall, endplates=inp.endplates,
               mech=inp.mech, m_wall=inp.m_wall, η_n_bare=inp.η_n_bare, C_struc=inp.C_struc, ρ0=inp.ρ0, c0=inp.c0)
end
spl(i, H) = 10log10(tone_mean_square_pressure(i, H, 2π * 200H) / (20e-6)^2)
base = [spl(inp, H) for H in 1:3]
io = IOBuffer()
println(io, "# H3 follow-up after the η_T correction (plan step 19i)\n")
println(io, "Generated by `scripts/checks/h3_followup.jl`. Criteria fixed 2026-10-20 before the run (`IMPLEMENTATION_PLAN.md`, step 19i). Inputs: 18b-r (R1 blocking, ANOPP Table 8, GEXT off the ℓ = 1 line, Phase III trim with η_T = 0.5): $(join([@sprintf("%.2f", b) for b in base], ", ")) dB against NASA $(join(nasa, ", ")) dB.\n")
println(io, "## Part A: structural-mode breakdown at η_T = 0.5 (no pass mark)\n")
tops = Dict{Int,Vector}()
for H in 1:3
    ωH = 2π * 200H
    tot = tone_mean_square_pressure(inp, H, ωH)
    parts = sort([(tone_mean_square_pressure(with_modes([m]), H, ωH), m) for m in inp.structural.modes]; by=first, rev=true)
    tops[H] = [m for (_, m) in parts[1:4]]
    println(io, "**H$H** (total $(round(spl(inp, H); digits=2)) dB, τ_t = $(round(PAIN.sidewall_tau(inp, ωH); sigdigits=3))):\n")
    println(io, "| structural mode | f (Hz) | symmetry | M_r (kg) | share of the sum | alone (dB) | top cabin mode (q, i, f Hz) by share |\n|---:|---:|---|---:|---:|---:|---|")
    for (p, m) in parts[1:4]
        # cabin mode carrying this structural mode
        a, L, c0 = inp.fuse.a, inp.fuse.L, inp.c0
        best = (0.0, nothing)
        θ0 = deg2rad(inp.fuse.theta0_deg); Lp = 2a * sin(θ0); V = PAIN.cabin_volume(inp.fuse); A = L * (Lp + 2a * (π - θ0))
        τ_t = PAIN.sidewall_tau(inp, ωH)
        ξ = PAIN.trim_conductance(inp.sidewall, ωH, inp.m_wall; ρ0=inp.ρ0, c0)
        ξe = PAIN.trim_conductance(inp.endplates, ωH, Inf; ρ0=inp.ρ0, c0)
        for q in 0:PAIN.axial_truncation(ωH, L, c0), ac in inp.acoustic.modes
            f = PAIN.coupling_factor(ac, m, inp.fuse; τ_t, q); f == 0 && continue
            ωn = 2π * PAIN.cabin_frequency_3d(ac, a, L, q; c0)
            N = PAIN.acoustic_loss_modal(ac, q, ωH, ωn; a, L, V, c0, ξ, ξ_e=ξe).N
            w = PAIN.cabin_eps_3d(ac, q) * f^2 / ((ωn^2 - ωH^2)^2 + N^2)
            w > best[1] && (best = (w, (q, ac.index, ωn / 2π)))
        end
        @printf(io, "| %d | %.1f | %s | %.2f | %.1f %% | %.2f | %s |\n", m.index, m.f_Hz, m.symmetric ? "S" : "A", m.M_r, 100p / tot, spl(with_modes([m]), H),
                best[2] === nothing ? "-" : @sprintf("(%d, %d, %.0f)", best[2]...))
    end
    println(io)
end

println(io, "## Part B: one omitted Table D-1 term, δ = ±0.057 (the 19g floor misfit), the four modes of H3\n")
println(io, "A term is added at the next integer n above the highest listed one (plate: `C_floor`/`n_floor`; shell: `C_shell`/`n_shell`); the printed M_r is kept. NASA PAIN at H3: $(nasa[3]) dB; base H3 $(round(base[3]; digits=2)) dB.\n")
println(io, "| structural mode | term | δ | H1 dB | H2 dB | H3 dB | shift H1, H2, H3 (dB) | H3 toward NASA ≥ 3 dB |\n|---:|---|---:|---:|---:|---:|---|---|")
function perturbed(m, which, δ)
    if which == :floor
        n = maximum(m.n_floor) + 1
        StructuralMode(m.index, m.f_Hz, m.symmetric, m.M_r, m.M_axial, m.C_shell, m.n_shell, vcat(m.C_floor, δ), vcat(m.n_floor, n)), n
    else
        n = maximum(m.n_shell) + 1
        StructuralMode(m.index, m.f_Hz, m.symmetric, m.M_r, m.M_axial, vcat(m.C_shell, δ), vcat(m.n_shell, n), m.C_floor, m.n_floor), n
    end
end
hits = String[]
δ0 = 0.057
for m in tops[3], which in (:floor, :shell), δ in (δ0, -δ0)
    pm, n = perturbed(m, which, δ)
    ms = [x.index == m.index ? pm : x for x in inp.structural.modes]
    try
        i2 = with_modes(ms)
        s = [spl(i2, H) for H in 1:3]
        toward = abs(s[3] - nasa[3]) <= abs(base[3] - nasa[3]) - 3
        toward && push!(hits, "mode $(m.index) $(which) n=$n δ=$(δ)")
        @printf(io, "| %d | %s n = %d | %+.3f | %.2f | %.2f | %.2f | %+.2f, %+.2f, %+.2f | %s |\n", m.index, which == :floor ? "plate" : "shell", n, δ, s..., (s .- base)..., toward ? "**yes**" : "no")
    catch e
        @printf(io, "| %d | %s n = %d | %+.3f | | | | not computed: %s | |\n", m.index, which == :floor ? "plate" : "shell", n, δ, first(split(sprint(showerror, e), '\n')))
    end
end
println(io, "\n**Result:** " * (isempty(hits) ? "no perturbation of this size moves H3 by 3 dB toward NASA; the omitted-term explanation of the floor-shape miss is **not found** as the cause of the H3 miss (it is not excluded for terms larger than 0.057)." :
                                   "implicated: " * join(hits, "; ") * ". Not adopted (the printed D-1 coefficients are NASA's values)."))
out = joinpath(@__DIR__, "..", "..", "..", "docs", "validation_reports", "h3_followup.md")
write(out, String(take!(io))); println(read(out, String))
