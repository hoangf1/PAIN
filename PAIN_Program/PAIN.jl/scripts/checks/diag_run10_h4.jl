"""Acoustic modes with the 2-D eigenvalue rescaled so that its part of f_n is at `c2d` while `cabin_frequency_3d` is called
with c_int (the axial part)."""
rescale2d(ac::PAIN.Cyl2DResult, c2d) = PAIN.Cyl2DResult(ac.theta0_deg, [PAIN.AcousticMode(m.index, m.f_Hz_unit, m.symmetric,
    m.gen_mass_unit, m.phi_boundary, m.theta_boundary_deg, m.eps_n, m.phi_floor, m.x_floor_unit, m.theta_lo_rad, m.theta_hi_rad,
    m.x_lo_unit, m.x_hi_unit, m.lambda_unit * (c2d / c_int)^2, Dict{Tuple{Int,Int},Float64}()) for m in ac.modes], ac.notes, ac.NY, ac.h, ac.c0)
cut53(m) = PAIN.StructuralMode(m.index, m.f_Hz, m.symmetric, m.M_r, m.M_axial, m.C_shell[1:min(5, end)], m.n_shell[1:min(5, end)],
                              m.C_floor[1:min(3, end)], m.n_floor[1:min(3, end)])
st_full = inp0.structural
st_53 = PAIN.StructuralModes(cut53.(st_full.modes), st_full.L, st_full.a, st_full.theta0_deg, st_full.notes)
ac_ship = inp0.acoustic
ac_grid = PAIN.cyl2d_modes(50.0; n_modes=20, NY=11, c0=c_int, node_tol=0.45)
ac_341 = rescale2d(ac_grid, 341.0)
pts_printed = [merge(q, (; theta_deg=-15.0 + 10.0 * (q.ell - 1), alpha_deg=abs(-15.0 + 10.0 * (q.ell - 1) - 75.0))) for q in inp0.pts]

function run10(; printed_theta=false, acoustic=ac_ship, structural=st_full, floor_sign=1.0)
    prop = printed_theta ? PAIN.PropellerPlacement(2.35, 75.0, 1.12) : inp0.prop
    pts = printed_theta ? pts_printed : inp0.pts
    inp = PAIN.PainInputs(inp0.fuse, prop, structural, acoustic, inp0.amplitudes, inp0.phases, pts, inp0.ΔA;
                     sidewall=inp0.sidewall, endplates=inp0.endplates, mech=nothing, m_wall=inp0.m_wall, L_c=Lc,
                     ρ_ext=inp0.ρ_ext, c_ext=inp0.c_ext, ρ_int=inp0.ρ_int, c_int, η_r_band=inp0.η_r_band,
                     allow_extrapolation=true, floor_sign)
    return inp, PAIN.interior_spl(inp; bpf_Hz=bpf, n_harmonics=4, broadband=false).harmonic_SPL_dB[2:4]
end

