function appb_eta(structural, fs)
    ok = 0; n = 0
    for (rpm, file) in ((4000, "appB_contributors_4000rpm.csv"), (5000, "appB_contributors_5000rpm.csv"))
        b = PAIN.r172428_inputs(rpm; structural)
        inp = PAIN.PainInputs(b.fuse, b.prop, b.structural, b.acoustic, b.amplitudes, b.phases, b.pts, b.ΔA; sidewall=b.sidewall,
                         endplates=b.endplates, mech=b.mech, m_wall=b.m_wall, L_c=b.L_c, ρ_ext=b.ρ_ext, c_ext=b.c_ext,
                         ρ_int=b.ρ_int, c_int=b.c_int, η_r_band=b.η_r_band, η_r_trimmed_area=b.η_r_trimmed_area, floor_sign=fs)
        V = PAIN.cabin_volume(inp)
        for r in rows(file)
            nasa = num(r, :eta_r_hash); nasa < 1e-4 && continue
            ours = PAIN._eta_r_pp_pair(inp, PAIN._acmode_by_I(inp, int(r, :I)), int(r, :Q), inp.structural.modes[int(r, :st_mode)], num(r, :f_Hz); V)
            ok += abs(ours / nasa - 1) ≤ 0.10; n += 1
        end
    end
    return "$ok/$n"
end
