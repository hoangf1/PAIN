"""Phase 155a (2026-11-15): write data/cr172428/appD_run10_H1.csv and appD_run10_H5.csv from the eye readings
(run10_H1_read.py, run10_H5_read.py) in the format of appD_run10_H2.csv.

Amplitude rows L = 1..9 are taken from rows 20 - L (PAIN prints the lower quarter as their mirror; the printed copies
were read too and agree, see check_mirror_rule.py). Phase rows are as printed; the rows cut at the page bottom (H1: L = 1;
H5: L = 1, 2) are generated by PAIN's lower-quarter rule phase(10 - j) = phase(10 + j) + H f_j (CR-172428 App. A item 5,
DELPH = 2 B IH ALPHAL(L)), with f_j from the fully printed H2-H4 fields. Run from this folder."""
import csv, importlib, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from check_mirror_rule import rule_steps, check
OUT = os.path.join(HERE, '..', '..', 'cr172428')
z = {}
for r in csv.DictReader(l for l in open(os.path.join(OUT, 'appD_run10_H2.csv'), encoding='utf-8') if not l.startswith('#')):
    z[int(r['k'])] = r['z_m']
f = rule_steps()
PAGES = {1: ('run10_H1_read', 'App. D p. 230 (PDF p. 240)', 104.5, [1]), 5: ('run10_H5_read', 'App. D p. 234 (PDF p. 244)', 522.7, [1, 2])}
for H, (mod, page, fHz, cut) in PAGES.items():
    m = importlib.import_module(mod)
    A = {L: [float(x) for x in s.split()] for L, s in m.AMP.items()}
    P = {L: [float(x) for x in s.split()] for L, s in m.PH.items()}
    _, bad = check(mod, H)
    phase_bad = [b for b in bad if b[0] == 'phase' and abs(b[6]) > 0.3]
    assert not phase_bad, phase_bad
    for L in cut:
        j = 10 - L
        P[L] = [round(((P[10 + j][k] + H * f[j] + 180) % 360) - 180, 1) for k in range(16)]
    path = os.path.join(OUT, 'appD_run10_H%d.csv' % H)
    with open(path, 'w', newline='\n', encoding='utf-8') as fo:
        fo.write('# NASA CR-172428 %s: propeller field PAIN used in flight-test run 10 (Merlin IVC, 4-blade Dowty Rotol,\n' % page)
        fo.write('# 1568 rpm), harmonic %d (%.1f Hz); 16 axial (k) x 19 circumferential (L) points. Columns and conventions as appD_run10_H2.csv.\n' % (H, fHz))
        fo.write('# Transcribed 2026-11-15 (Phase 155a) by eye from 300 dpi crops (data/digitizers/cr172428_run10/), doubtful cells at 600 dpi.\n')
        fo.write('# Checked against the print itself: every input row L = 10..19 is printed again in the lower quarter (amplitude as its\n')
        fo.write('# mirror, phase by PAIN\'s rule within 0.3 deg); disagreements were re-read and are listed in the reading file.\n')
        fo.write('# Amplitude rows L = 1..9 = rows 20 - L. Phase rows L = %s are cut in the scan and generated by PAIN\'s lower-quarter rule\n' % ', '.join(str(c) for c in cut))
        fo.write('# (App. A item 5, DELPH = 2 B IH ALPHAL); that rule reproduces every printed lower phase of H2-H4 to 0.1 deg.\n')
        if H == 1:
            fo.write('# Row L = 10 (no printed mirror): the decimal 4 and 6 are not certain in the underlined row at k = 1, 2, 4, 8, 12 (+-0.2 dB).\n')
        fo.write('L,theta_print_deg,k,z_m,amp_dB,phase_deg\n')
        for L in range(1, 20):
            amp = A[20 - L] if L < 10 else A[L]
            for k in range(1, 17):
                fo.write('%d,%d,%d,%s,%.1f,%.1f\n' % (L, 10 * (L - 1) - 15, k, z[k], amp[k - 1], P[L][k - 1]))
    print('wrote', path)
